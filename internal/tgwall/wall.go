// Тип источника сообщения. По нему выбирается цвет левой границы карточки
// и маркера у тега (точки или счётчика непрочитанных), и форма заголовка.
type cardType int

const (
	cardChannel cardType = iota
	cardChat
	cardPersonal
)

// card — одна карточка стены.
type card struct {
	Type cardType
	// Name — название канала/чата либо имя отправителя в личном диалоге.
	Name string
	// Author — отправитель в чате (в канале и личном не используется).
	Author string
	// AuthorSignature — подпись автора поста в канале, если она есть.
	AuthorSignature string
	Time            string
	Text            string
	Tag             string
	// UnreadCount — непрочитанные в источнике, как их знает TDLib на момент
	// снимка (auth.Chat.UnreadCount) и на момент последнего живого апдейта
	// updateChatReadInbox. На экране показывается в блоке тега вместо точки
	// (см. unreadMarker), и в карточке не участвует больше нигде: ни заголовок,
	// ни текст от него не зависят.
	UnreadCount int32
	// ChatID и MessageID — адрес карточки внутри Telegram: по этой паре
	// дедуплицируется повтор того же сообщения (гонка «сообщение уже есть в
	// снимке, апдейт пришёл по нему же») и удерживается курсор на том же
	// сообщении после того, как вставка сдвинула индексы. На экране они не
	// показываются, но без них живых апдейтов на стене не сделать вовсе.
	ChatID    int64
	MessageID int64
	// Date — время сообщения, как пришло от TDLib. Отдельное поле от Time
	// (готовой строки для показа): по строке нельзя сортировать вставку.
	Date int64
	// Outgoing — своё ли это сообщение. Карточке стены поле не нужно: там видно
	// по метке «Вы:» в тексте, а заголовок сторону не различает. В открытой
	// переписке (задача 0155) это признак стороны блока: входящий прижат к
	// левому краю, свой — к правому, а метка «Вы:» не рисуется вовсе, потому
	// что сторона и так говорит всё. Заполняет только конструктор сообщения
	// переписки (zoomCard) — карточка стены сюда ничего не кладёт.
	Outgoing bool
	// ReadByPeer — прочитано ли СВОЁ сообщение собеседником: у исходящего с
	// id не выше LastReadOutboxMessageID (auth.Chat.LastReadOutboxMessageID).
	// Именно «собеседником», а не «мной»: прочитать своё сообщение я не могу,
	// и смешивать два состояния в одном поле значило бы потом гадать, что
	// означает его значение. Заполняет только zoomCard — карточка стены
	// галочек не рисует (у неё на строке времени стоит сведения об источнике,
	// см. renderWallCard). Не путать с UnreadCount: тот — счётчик
	// НЕПРОЧИТАННЫХ ВХОДЯЩИХ у карточки стены, вещь другая и живёт в другом
	// месте (updateChatReadInbox).
	ReadByPeer bool
	// ReplyQuote — короткая одностроч­ная цитата оригинала, если сообщение —
	// ответ (auth.Message.ReplyQuote, уже разобрана и обрезана в internal/auth,
	// parseReplyQuote). Пусто, если ответа нет. Заполняет только zoomCard —
	// карточка стены вшивает свой собственный признак ответа прямо в Text (см.
	// wallCard), потому что там всё сжато в одну строку и второе поле было бы
	// лишней сущностью без выгоды.
	ReplyQuote string
	// PeerID — id объекта, на который указывает ТИП чата: user_id для личного
	// диалога, basic_group_id/supergroup_id для группы и канала. Именно по нему
	// находятся живые значения (число участников, статус собеседника) в кэше
	// модели, поэтому само поле — обсиротевшее без кэшей число, и на экране оно
	// не показывается никогда. Смысл различает Type: у одного и того же int64
	// два разных пространства идентификаторов, и читать его без Type нельзя.
	PeerID int64
	// MemberCount — число участников группы или подписчиков канала, как его
	// знает TDLib (member_count в basicGroup/supergroup) на момент снимка и на
	// момент последнего живого апдейта updateBasicGroup/updateSupergroup.
	// Показывается компактной записью рядом с именем (см. memberCountText);
	// ноль или отрицательное значение («данных нет») не показывается вовсе.
	MemberCount int32
	// Status — статус собеседника по данным TDLib (user.status) для ЛИЧНОГО
	// диалога. Показывается рядом с именем (см. userStatusText); у групп и
	// каналов не заполняется — там на его месте MemberCount.
	Status auth.UserStatus
	// SelectionAccent — цвет, которым рисуется маркер курсора в открытой
	// переписке (см. renderZoomMessage): акцент ТИПА открытого чата, а не
	// карточки под курсором стены. Заполняет только Model при отрисовке
	// переписки (zoomCardsOf по карточке источника из m.source) — карточка стены
	// это поле не читает, её собственный акцент берётся из Type.
	//
	// Отдельное поле, а не переиспользование Type: у сообщения переписки типа
	// источника нет по построению (zoomCard не знает чата), и проставлять Type
	// значило бы врать — карточка стены того же сообщения отличалась бы от
	// переписочной только этим полем, а различаться они не должны.
	SelectionAccent color.Color
	// Muted — источник заглушен по-своему (auth.Chat.Muted). На карточке не
	// показывается нигде: это признак для фильтра «Приглушённые» (см.
	// wallFilter.allows), и держать его на карточке нужно ровно затем, что
	// фильтр получает карточку, а не чат.
	Muted bool
}

// wallCard — карточка из пары «чат TDLib + его сообщение». Единственное место,
// где auth.Chat и auth.Message превращаются в карточку стены.
//
// Поле Tag — по типу чата, а не по наличию автора: у личного диалога отправитель
// есть всегда, но показывать его отдельно в заголовке не нужно (см. title), и
// тег «#личное» читается ровно так же, как «#чат» или «#канал», независимо от
// того, кто написал.
//
// Author заполняется у всех типов, хотя в заголовке читается только у cardChat:
// поле нужно личному диалогу, где title() показывает имя чата, а это имя
// отправителя (у личного чата title TDLib — фамилия, а показывать там
// «Чат — Марина» значило бы дублировать одно и то же). Сохранение лишнего поля
// в карточке дешевле ветки с потерей данных, а удалять его придётся, когда
// личные диалоги дорастут до чего-то вроде «Чат — прочитано».
//
// cardTypeOf — единственное место, где auth.ChatKind переводится в тип карточки,
// чтобы три места выбора не разошлись при правке.
func wallCard(chat auth.Chat, message auth.Message) card {
	kind := cardTypeOf(chat.Kind)
	author := message.SenderName
	text := normalizeMessageText(message.Text)
	// Сообщение-ответ помечается тем же знаком (wallReplyMarker), что и строка
	// контекста над полем ввода при составлении ответа: карточка стены иначе
	// никак не отличалась от обычного сообщения (человек заметил это вживую,
	// 2026-09-30 — «в чате и на стене не видно, что это ответ»). ReplyQuote уже
	// готов к показу — короткая одностроч­ная цитата, разобрана в internal/auth
	// (parseReplyQuote), обрезка там же.
	if message.ReplyQuote != "" {
		text = wallReplyMarker + " " + message.ReplyQuote + ": " + text
	}
	if message.IsOutgoing {
		if kind == cardChat {
			// В заголовке чата уже есть отдельный слот под автора (title()
			// показывает «[Чат — Автор]») — заменяем настоящее имя на «Вы», а
			// не дублируем это же ещё и в тексте.
			author = outgoingLabel
		} else {
			// У канала и личного диалога в заголовке нет слота под автора (там
			// всегда одно имя — самого источника, не того, кто написал), и без
			// метки в тексте человек не отличил бы своё сообщение от чужого,
			// глядя на голую строку (см. брейншторм с человеком — «непонятно,
			// что я писал, что мне писали»).
			text = outgoingLabel + ": " + text
		}
	}
	return card{
		Type:            kind,
		Name:            chat.Title,
		Author:          author,
		AuthorSignature: message.AuthorSignature,
		Time:            auth.FormatMessageTime(message.Date),
		Text:            text,
		Tag:             cardTagOf(kind),
		UnreadCount:     chat.UnreadCount,
		ChatID:          chat.ID,
		MessageID:       message.ID,
		Date:            message.Date,
		// PeerID — ключ, по которому к этой карточке потом находятся живые
		// сведения об источнике (счётчик участников у группы и канала, статус у
		// личного диалога). Сами значения приходят апдейтами позже и докладываются
		// через syncWallSourceInfo, поэтому здесь их нет.
		PeerID: chat.PeerID,
		Muted:  chat.Muted,
	}
}

// outgoingLabel — как показывается отправитель собственных сообщений: то же
// соглашение, что у Telegram/WhatsApp/iMessage в превью списка чатов, а не
// настоящее имя аккаунта (человек и так знает, кто он).
const outgoingLabel = "Вы"

// normalizeMessageText — текст сообщения с сохранённой структурой абзацев
// (настоящий перенос строки остаётся границей строки), но без лишних пробелов
// внутри каждой отдельной строки. Раньше (до находки человека про «вернуть
// абзацы») перенос строки схлопывался в пробел ВСЕГДА, и сообщение с пунктами
// (отчёт бота, список) превращалось в один сплошной абзац — то, из-за чего
// оригинальная структура терялась даже там, где её безопасно показать.
//
// Раз в card.Text теперь может быть настоящий "\n", ответственность за то, чтобы
// он не попал в терминал НЕ через wrapVisible (текст карточки стены — всегда
// ровно одна строка экрана, см. вторую строку renderCard), лежит на самой
// отрисовке: см. collapsedText. Не убирать перенос здесь: сохранять структуру
// абзацев нужно будущему экрану одного чата (задача 0155), где полный текст
// читается целиком, — а убирать его молча на стене — обязанность рендера, а не
// этой функции.
func normalizeMessageText(text string) string {
	lines := strings.Split(text, "\n")
	normalized := make([]string, len(lines))
	for index, line := range lines {
		normalized[index] = strings.Join(strings.Fields(line), " ")
	}
	return strings.Join(normalized, "\n")
}

// flattenToSingleLine — текст одной строкой, без переносов и лишних пробелов.
// В отличие от normalizeMessageText (хранит структуру абзацев), это для мест, где
// абзацы не нужны в принципе — например, короткая цитата в строке ответа над
// полем ввода (см. replyLabel в send.go): многострочная цитата над полем
// выглядела бы чужеродно рядом с однострочной подсказкой.
func flattenToSingleLine(text string) string {
	return strings.Join(strings.Fields(text), " ")
}

// firstLineOf — текст до первого настоящего переноса строки и признак, что
// после него есть ещё текст (значит, оригинальное сообщение — не одна строка).
func firstLineOf(text string) (line string, hasMore bool) {
	if index := strings.IndexByte(text, '\n'); index >= 0 {
		return text[:index], true
	}
	return text, false
}

// collapsedText — текст карточки стены: гарантированно ровно одна строка
// экрана, без единого сырого переноса строки (это и есть защита от прежнего
// бага — «отчёт бота ломает сетку строк стены», см. normalizeMessageText). Если
// у сообщения есть ещё абзацы, это тоже «не поместилось», и получает тот же
// знак «…», что и обрезка по ширине — иначе карточка многострочного сообщения
// выглядела бы так, будто оно и есть целиком одна строка. Отдельного знака «есть
// продолжение» больше нет (задача 0156): обрезка по ширине и настоящий перенос
// строки теперь различаются тем же «…», что и раньше.
func collapsedText(text string, width int) string {
	first, hasMore := firstLineOf(text)
	rendered := truncateVisible(first, width)
	if hasMore && rendered == first {
		// Первая строка сама поместилась без обрезки по ширине — обрезаем явно
		// ради многоточия, тем же truncateVisible, чтобы не заводить второй
		// способ добавить многоточие.
		rendered = truncateVisible(first+ellipsis, width)
	}
	return rendered
}

func cardTypeOf(kind auth.ChatKind) cardType {
	switch kind {
	case auth.ChatChannel:
		return cardChannel
	case auth.ChatGroup:
		return cardChat
	default:
		return cardPersonal
	}
}

func cardTagOf(source cardType) string {
	switch source {
	case cardChannel:
		return "#канал"
	case cardChat:
		return "#чат"
	default:
		return "#личное"
	}
}

// title — заголовок карточки по типу источника: у канала и личного диалога
// одно имя, у чата — «чат — автор», у канала с подписью — «канал — подпись».
// Без скобок вокруг имени (были у всех трёх веток — убраны по прямой просьбе
// человека, 2026-09-30): тип источника и так виден по цвету левой границы и
// тегу, скобки были лишним визуальным шумом.
func (c card) title() string {
	switch c.Type {
	case cardChannel:
		if c.AuthorSignature != "" {
			return c.Name + " — " + c.AuthorSignature
		}
		return c.Name
	case cardChat:
		return c.Name + " — " + c.Author
	default:
		return c.Name
	}
}

// accent — цвет типа источника: им красится и левая граница карточки, и
// маркер у тега справа.
func (c card) accent() color.Color {
	switch c.Type {
	case cardChannel:
		return PaletteChannel
	case cardChat:
		return PaletteChat
	default:
		return PalettePersonal
	}
}

// Ширины колонок карточки — из макета, в ячейках терминала. Заголовок, время и
// тег не тянутся по ширине окна: их ширина фиксирована, и от окна зависит
// только текст сообщения.
const (
	// cardMarginH — боковые поля экрана, в которых стоят карточки. Те же два
	// отступа, что у карточек ленты tgcli.
	cardMarginH = 2
	// cardBorderWidth — колонка ┃ слева от каждой строки карточки.
	cardBorderWidth = 1

	cardTimeWidth = 5
	// cardTitleInfoMaxWidth — жёсткий потолок ширины блока «имя + сведения» на
	// строке 1, считая от начала содержимого карточки (после отступа и левой
	// границы). Имя стоит сразу перед сведениями без набивки до фиксированной
	// колонки: короткое имя не тянет их пустотой вправо (см. cardTitleText).
	// Если блок не влезает в этот потолок — обрезается ИМЯ (многоточием
	// truncateVisible), сами сведения не обрезаются никогда.
	//
	// Значение 65 зафиксировано человеком явно (2026-09-30) для блока «имя +
	// время» и не выводится из прочей геометрии карточки. Время с этой строки
	// ушло в конец строки текста (задача 0163), но потолок остался прежним и
	// теперь ограничивает «имя + сведения»: у личного диалога это «в сети», у
	// группы и канала — счётчик участников, то есть ровно та же роль, что была
	// у времени.
	cardTitleInfoMaxWidth = 65
	// cardTagWidth — колонка тега целиком: самый длинный тег («#личное», 7
	// ячеек) + cardTagLabelGapWidth (два пробела) + самый широкий маркер
	// («[99+]», 5 ячеек) = 14. Раньше здесь было 10 — хватало на тег с точкой,
	// но не на счётчик: обрезка под самый широкий маркер ужимала бы название
	// тега ровно в обычном случае (уже на однозначном счётчике), то есть
	// читаемость тега платила бы за то, что счётчик в 99+ встречается редко.
	// Колонка расширена один раз здесь, а не подгоняется веткой кода под
	// конкретный маркер: в renderCardTag она подставляется прямо в добивку по
	// этой ширине.
	cardTagWidth = 14
	// cardTagLabelGapWidth — зазор между названием тега и маркером у правого
	// края колонки. Отдельная константа, потому что renderCardTag использует
	// его дважды: один раз вычитает из ширины колонки, второй заполняет
	// пробелами, — и две записи по отдельности разъехались бы при правке
	// любой из них.
	cardTagLabelGapWidth = 2
	// cardUnreadMarkerMaxWidth — ширина самого широкого маркера непрочитанных,
	// «[99+]». Этой ширины достаточно для колонки тега там, где сам тег не
	// выводится: в суженной колонке стены рядом с панелью переписки (задача
	// 0155) карточка шириной 30, и колонка в cardTagWidth оставляла бы на имя
	// три символа. Маркер при этом рисуется и там — это сигнал «есть что
	// прочитать», а не часть тега.
	cardUnreadMarkerMaxWidth = 5
	cardSegmentGapWidth      = 1
)

// cardTitleInfo — сведения об источнике, которые показываются на строке 1 сразу
// за именем: у личного диалога это «в сети»/«был(а) недавно» и т.п., у группы и
// канала — число участников или подписчиков. Для обоих типов это единственное,
// что живого приходит в карточку по этому апдейту (см. applyWallMemberCountUpdate
// и applyWallUserStatusUpdate), и оба приходят одним и тем же способом: сначала
// снимок карточки, потом живые апдейты, поэтому место под них зарезервировано
// одинаково.
//
// Пустая строка — показывать нечего (личный чат без статуса, или данные ещё не
// пришли). Считать это заражённым случаем не надо: пустая строка не занимает ни
// ячейки и не сдвигает имя.
func cardTitleInfo(c card) string {
	if c.Type == cardPersonal {
		return userStatusText(c.Status, timeNow())
	}
	return memberCountText(c.MemberCount)
}

// cardTitleText — заголовок карточки как он попадёт на экран: обрезан так,
// чтобы вместе с зазором и сведениями не выйти за cardTitleInfoMaxWidth и не
// вылезти за колонку тега.
//
// ПРИОРИТЕТ — У ИМЕНИ (решение человека, 2026-10-01): сведения не занимают
// место заранее, а получают то, что останется после имени. Раньше было наоборот —
// ширина сведений вычиталась из доступной первой, и при длинных сведениях вроде
// «был(а) на этой неделе» имя уезжало в пустоту даже там, где оно влезло бы
// много раз: на 22 ячейках показывались одни сведения без имени вовсе. Имя — то,
// чем чат опознаётся, и под сведения его терять нельзя.
//
// available — ширина, реально доступная под «имя + сведения» после вычета
// отступа от границы, зазора и колонки тега (см. renderWallCard).
func cardTitleText(c card, available int) string {
	maxPrefix := min(cardTitleInfoMaxWidth, available)
	infoWidth := cellWidth(cardTitleInfo(c))
	if infoWidth == 0 {
		return truncateVisible(c.title(), maxPrefix)
	}
	// Место под сведения вычитается, но НЕ больше половины доступного: иначе
	// длинные сведения съедали бы имя целиком (на 22 ячейках «был(а) на этой
	// неделе» оставляло под имя ровно ноль). Имя получает место первым, а
	// сведения — остаток, который после этого ещё остался (см.
	// cardTitleInfoFits: если остатка не хватило, они не рисуются вовсе).
	reserved := min(infoWidth+cardSegmentGapWidth, maxPrefix/2)
	return truncateVisible(c.title(), max(0, maxPrefix-reserved))
}

// cardTitleInfoFits — поместятся ли сведения рядом с именем в отведённой ширине.
// Если нет — они не рисуются вовсе (см. renderWallCard).
func cardTitleInfoFits(c card, available int) bool {
	info := cardTitleInfo(c)
	return info != "" && cellWidth(info)+cardSegmentGapWidth <= available
}

// renderCard — карточка стены, готовая к вставке в экран: ровно две строки,
// вместе с боковыми полями и фоном карточки.
//
// Формат двухстрочный (макет CompactCard.dc.html): строка 1 — заголовок, сведения
// об источнике и (при условии ниже) блок тега у правого края, строка 2 — текст
// сообщения с отступом в одну ячейку и временем в самом конце. Время ушло со
// строки 1 на строку 2 (задача 0163, по прямому указанию человека «как в
// Telegram»): на строке 1 оно занимало место, которое теперь нужно сведениям об
// источнике, а тексту сообщения время по естеству принадлежит.
func renderCard(c card, width int, selected bool) []string {
	return renderWallCard(c, width, selected, false, false)
}

// renderWallCard — карточка стены в двух особых режимах, которые заводит широкая
// раскладка с панелью переписки (задача 0155).
//
// hidePreview — у карточки под курсором не показываются ни текст последнего
// сообщения, ни время (вместе с ним), ни сведения об источнике: та же переписка
// открыта справа целиком. Прямое указание человека (2026-09-30): «у того имени
// которое выделено нет смысла во времени и последнем сообщении».
//
// panelColumn — карточка рисуется в суженной колонке стены рядом с панелью, а не
// во весь экран. Влияет только на блок тега (см. ниже): в колонке шириной 30 тег
// съел бы половину карточки.
//
// Геометрия карточки от обоих флагов не зависит — блок остаётся ровно
// двухстрочным, — поэтому окну прокрутки стены не нужен второй способ измерить
// карточку, и wallCardHeight остаётся единственным. Отличается только наполнение
// строк, поэтому это флаги у той же отрисовки, а не условный рендер поверх
// готового результата.
func renderWallCard(c card, width int, selected, hidePreview, panelColumn bool) []string {
	// Обычная строка сливается с фоном экрана — тип виден по цвету левой границы,
	// а не по отдельному "боксу" вокруг каждой карточки. Выделенная красится в
	// PaletteBackgroundSelected — заметно светлее и фона экрана, и фона панели
	// поля ввода, чтобы не путать «это сейчас в фокусе» с «это просто панель».
	// Фон ОДИН на обе строки: выделение, красящее одну строку из двух, читалось
	// бы как «карточка началась/кончилась», а не как «карточка выбрана».
	background := PaletteBackgroundMain
	if selected {
		background = PaletteBackgroundSelected
	}
	bodyWidth := width - 2*cardMarginH - cardBorderWidth
	if bodyWidth <= 0 {
		return nil
	}

	// Превращается в пустую строку, когда у выбранной карточки нечего
	// показывать: та же переписка уже открыта справа целиком. Считается на
	// копии карточки (card — тип-значение, копия бесплатна), а не отдельной
	// формулой: тогда и заголовок, и обрезка текста остаются ровно теми же
	// функциями, что и в обычном случае.
	shown := c
	if hidePreview {
		shown.Time = ""
		shown.Text = ""
		shown.MemberCount = 0
		shown.Status = auth.UserStatus{}
	}

	gap := renderedFill(cardSegmentGapWidth, background)
	// available — вся ширина карточки после границы ┃, без дополнительного
	// отступа: человек попросил убрать его (2026-09-30) — содержимое начинается
	// сразу за границей.
	available := bodyWidth

	// Имя стоит сразу перед сведениями, без набивки до фиксированной колонки:
	// короткое имя не тянет их пустотой вправо (человек это заметил вживью
	// 2026-09-30 на строке с временем, и правило осталось тем же после его
	// переезда на строку текста). Обрезается по cardTitleText — там же и жёсткий
	// потолок cardTitleInfoMaxWidth, сами сведения там не обрезаются никогда.
	//
	// Колонка тега вычитается из доступной ширины заголовка ВСЕГДА, независимо от
	// того, показан ли сам тег: маркер непрочитанных рисуется в ней в любом
	// случае, то есть место под неё занято. Считать её иначе (вычитать только
	// когда тег нарисован) значило бы сдвинуть заголовок у невыделенных
	// карточек, у которых тега нет.
	//
	// tagWidth — ширина блока тега справа: в суженной колонке рядом с панелью
	// переписки это ровно маркер непрочитанных, во всю ширину стены — весь блок
	// вместе с текстом тега.
	//
	// В суженной колонке (шириной wallPanelColumnWidth = 30) блок тега в
	// cardTagWidth (14) съедал бы больше половины карточки: от 25 ячеек
	// содержимого на «имя + сведения» оставалось бы 9, и любой источник на стене
	// выглядел бы как «[Н…» (проверено вживью). Там резервируется ровно маркер
	// (cardUnreadMarkerMaxWidth), потому что тег в колонке не выводится вовсе, а
	// маркер нужен и там — это сигнал «есть что прочитать», а не украшение.
	//
	// prefixAvailable считается здесь же, а не отдельной функцией: ширина блока
	// тега выбирается ровно здесь, и любое второе место, где она вычисляется
	// снова, — это уже два ответа на один вопрос, которые разъедутся при первой
	// же правке (так и случилось, пока эта арифметика жила ещё и в тесте).
	tagWidth := cardTagWidth
	if panelColumn {
		tagWidth = cardUnreadMarkerMaxWidth
	}
	prefixAvailable := max(0, available-cardSegmentGapWidth-tagWidth)
	titleStyle := lipgloss.NewStyle().Foreground(PaletteText).Bold(true).Background(background)
	// Сведения вставляются только когда они есть: пустая строка не должна
	// оставлять после имени лишний зазор, из-за которого у личного чата без
	// статуса и у группы, чей счётчик ещё не пришёл, имя съезжало бы влево
	// относительно карточек со сведениями.
	prefix := titleStyle.Render(cardTitleText(shown, prefixAvailable))
	// Сведения показываются везде, включая узкую колонку рядом с панелью
	// переписки (человек попросил вернуть это, 2026-09-30, — раньше здесь стоял
	// явный запрет !panelColumn, добавленный при ревью 0163 из-за находки
	// «короткое имя + сведения протекают в узкую колонку»; сама протечка была
	// не багом раскладки — cardTitleText и так резервирует под сведения место,
	// урезая бюджет ИМЕНИ на их ширину (см. её же тело), а не наоборот).
	// Сведения показываются ВСЕГДА, пока не пустые, независимо от длины имени —
	// тот же принцип, что и в компактном режиме с задачи 0163, узкая колонка
	// здесь не исключение.
	// Сведения показываются, только если на них осталось место ПОСЛЕ имени (см.
	// cardTitleInfoFits). Приоритет у имени: раньше сведения рисовались всегда и
	// вытесняли имя в пустоту, из-за чего в суженной колонке панели на 22 ячейках
	// карточка личного диалога показывала одно «был(а) на этой неделе» без
	// имени (решение человека, 2026-10-01).
	if info := cardTitleInfo(shown); info != "" && cardTitleInfoFits(shown, prefixAvailable) {
		prefix += gap + foregroundBackgroundStyle(PaletteTextMuted, background).Render(info)
	}

	// Блок тега показывается только у ВЫБРАННОЙ карточки, и только когда стена
	// занимает весь экран: в широком режиме это же место со временем отдано
	// боковой панели переписки (задача 0155), и повторять там же тег избыточно —
	// человек прямо об этом попросил (2026-09-30), то же решение уже было в
	// брейншторме («в три колонки — тег не выводить»), позиция и так говорит о
	// типе источника. Маркер непрочитанных при этом остаётся ВСЕГДА: это не тег,
	// а отдельный сигнал «есть что прочитать» (задача 0153), скрывать его вместе
	// с тегом было бы явной потерей функции.
	//
	// Порог «показывать тег» сравнивается с шириной ТЕРМИНАЛА, а renderWallCard
	// знает только ширину ЗОНЫ, поэтому в режиме панели решение принимается сверху
	// (panelColumn) и порог не применяется вовсе.
	//
	// Без этого разделения колонка шириной 30 всегда читалась бы как «узкий
	// терминал»: тег выводился бы в ней и съедал 14 ячеек из 25, обрезая заголовок
	// до трёх символов («[Н…») у КАЖДОЙ карточки — ровно то, чего человек просил
	// избежать, отдав это место панели переписки.
	showTagLabel := selected && !panelColumn && width <= cardTitleInfoMaxWidth
	// Заголовок со сведениями занимает всю оставшуюся ширину минус зазор и блок
	// тега, а тег дописывается справа — так его правый край совпадает с правым
	// краем карточки у ЛЮБОЙ карточки, независимо от длины заголовка (тот же
	// баг с выравниванием, что ловили в задаче 0147).
	headline := fitLine(prefix, prefixAvailable, background) +
		gap + renderCardTag(shown, background, showTagLabel, tagWidth)

	// Время — свой фиксированный суффикс в конце строки ТЕКСТА, а не часть
	// заголовка (задача 0163, «как в Telegram»: «текст сообщения … 13:04»).
	// Тот же приём, что уже применён у времени в переписке (см. alignedLine в
	// zoom.go): текст обрезается на всё, что осталось после времени и зазора, а
	// время не обрезается и стоит у правого края строки у ЛЮБОЙ карточки.
	// Обрезается именно текст, а не переносится время на свою строку — прямое
	// указание человека.
	//
	// В ШИРОКОМ РЕЖИМЕ (panelColumn) время не рисуется вовсе (прямое указание
	// человека, 2026-10-01): узкая колонка стены рядом с перепиской и так отдаёт
	// место тексту, а та же переписка открыта справа целиком, где время у каждого
	// сообщения есть. Время у карточки под курсором уже скрыто по той же причине
	// (hidePreview) — теперь это правило распространилось на всю колонку, а не
	// только на выбранную карточку.
	//
	// В узком режиме (стена во всю ширину терминала, панели нет) время остаётся:
	// там переписки нигде нет, и время последнего сообщения — единственный
	// признак свежести карточки.
	//
	// Само время обрезается по cardTimeWidth и не выходит за пределы available:
	// на совсем узкой карточке (суженная колонка) под него может не остаться
	// места вовсе — тогда текст не показывается вовсе, а время показывается
	// сколько влезает, тот же приём «показать столько, сколько влезает», что и у
	// collapsedText с обрезкой по ширине.
	shownTime := shown.Time
	if panelColumn {
		shownTime = ""
	}
	timeWidth := min(cellWidth(truncateVisible(shownTime, cardTimeWidth)), available)
	textWidth := max(0, available-timeWidth-cardSegmentGapWidth)
	// Зазор рисуется только когда есть что разделять: на совсем узкой карточке
	// под текст места не осталось, и лишний пробел съел бы последнюю ячейку
	// самого времени.
	timeGap := ""
	if textWidth > 0 && shownTime != "" {
		timeGap = gap
	}
	// Текст приглушён (PaletteTextMuted) — он вторичен по отношению к
	// заголовку, а подсветка смысловых токенов поверх приглушённого цвета
	// сохраняется. У выбранной карточки текст ярче (PaletteText, как в мокапе
	// CompactCard.dc.html — «фон светлее на обе строки сразу, текст ярче»):
	// приглушённость означает «сейчас не в фокусе», а не «текст менее важен,
	// чем заголовок». Время на этой строке приглушено всегда, даже у
	// выбранной карточки: это подпись к сообщению, а не часть заголовка, и на
	// строке заголовка время было приглушенным точно так же.
	textColor := PaletteTextMuted
	if selected {
		textColor = PaletteText
	}
	text := fitLine(highlightText(collapsedText(shown.Text, textWidth), textColor, background),
		textWidth, background) +
		timeGap +
		fitLine(foregroundBackgroundStyle(PaletteTextMuted, background).
			Render(truncateVisible(shownTime, cardTimeWidth)), timeWidth, background)

	margin := renderedFill(cardMarginH, PaletteBackgroundMain)
	// Левая граница — на ОБЕИХ строках: по одной ячейке границы читалось бы, что
	// граница есть только у заголовка, а не у карточки.
	//
	// Акцентный цвет источника — только у ВЫДЕЛЕННОЙ карточки, единым правилом в
	// обоих режимах (panelColumn и обычная стена): человек заметил вживую
	// (2026-09-30), что десяток разноцветных линий подряд пестрит — сначала это
	// приглушили только в узкой колонке, затем распространили на всю стену.
	// Невыделенная карточка — фон вместо PaletteBorder (человек прямо попросил
	// убрать серые полоски у всего списка, 2026-09-30): столбец границы остаётся
	// зарезервированным (bodyWidth/available её уже учитывают), просто невидим.
	borderColor := background
	if selected {
		borderColor = c.accent()
	}
	border := foregroundBackgroundStyle(borderColor, background).Render("┃")
	return []string{
		margin + border + fitLine(headline, bodyWidth, background) + margin,
		margin + border + fitLine(text, bodyWidth, background) + margin,
	}
}

// renderCardTag — блок тега справа строки 1: приглушённый текст, два пробела и
// маркер у самого правого края колонки (по прямому указанию человека — раньше
// точка стояла перед текстом). Маркер — точка, когда непрочитанных нет, и счётчик
// в квадратных скобках, когда есть (см. unreadMarker).
//
// showLabel — показывать ли сам текст тега («#канал» и т.п.): когда false,
// рисуется только маркер, но правый край колонки тот же — маркер не должен
// прыгать по колонке в зависимости от того, показан рядом текст тега или нет (тот
// же принцип, что и с зарезервированной колонкой знака «продолжение» в задаче
// 0154).
//
// width — ширина всей колонки, ровно та, какая вычтена из доступной ширины
// заголовка (см. renderWallCard). Параметром, а не константой: в суженной колонке
// рядом с панелью переписки резервируется только маркер, и колонка тега там уже
// не cardTagWidth. Считать бы её тут по своей константе значило бы разъехаться с
// арифметикой заголовка, то есть получить блок шире отведённого.
func renderCardTag(c card, background color.Color, showLabel bool, width int) string {
	content := foregroundBackgroundStyle(c.accent(), background).Render(unreadMarker(c))
	if showLabel {
		name := truncateVisible(c.Tag, max(0, width-cardTagLabelGapWidth))
		label := foregroundBackgroundStyle(PaletteTextMuted, background).Render(name)
		content = label + renderedFill(cardTagLabelGapWidth, background) + content
	}
	return renderedFill(max(0, width-cellWidth(content)), background) + content
}

// unreadMarker — что стоит у самого правого края тега: ничего (непрочитанных
// нет) или счётчик в квадратных скобках, тем же акцентным цветом источника.
// Точки-заглушки здесь раньше не было — убрана по прямому указанию человека
// (2026-09-30, «не нравятся»): renderCardTag и так не оставляет лишнего зазора
// на пустом content (см. его же комментарий про cardTitleInfo). Ноль и
// отрицательное значение дают пустую строку: на живых данных отрицательного
// не бывает, а в тестовых карточках ноль — обычное «непрочитанных нет».
//
// unreadMarkerCap и unreadMarkerCapLabel — предел счётчика непрочитанных и его
// подпись в маркере. Число и подпись живут рядом, и оба места, где маркер
// появляется, собираются из них: сравнение «больше 99» и сам «[99+]». Раньше
// «99» было зашито дважды — в сравнении и внутри строки, — и правка одной из
// двух записей тихо оставила бы на экране маркер, не сходящийся с пределом.
//
// Предел в 99 — тот же, что общепринят в мессенджерах (Telegram включительно):
// трёхзначные и больше числа раздувают колонку тега неограниченно, а сама
// точная цифра после сотни человеку не важна, важен факт «много».
const (
	unreadMarkerCap      = 99
	unreadMarkerCapLabel = "99+"
)

func unreadMarker(c card) string {
	switch {
	case c.UnreadCount <= 0:
		return ""
	case c.UnreadCount > unreadMarkerCap:
		return "[" + unreadMarkerCapLabel + "]"
	default:
		return fmt.Sprintf("[%d]", c.UnreadCount)
	}
}

// clampWallCursor — курсор стены в границах списка: у пустой стены он
// остаётся в нуле, иначе зажимается по краям, чтобы не уехал за карточки.
func clampWallCursor(cursor, count int) int {
	if count <= 0 {
		return 0
	}
	if cursor < 0 {
		return 0
	}
	if cursor >= count {
		return count - 1
	}
	return cursor
}

// wallGap — зазор между соседними карточками стены: одна пустая строка основного
// фона. Та же константа, по которой renderWall раздвигает карточки, и по которой
// считается всё окно прокрутки: разные числа в этих двух местах означали бы, что
// окно прокручивается не по тому, что на самом деле нарисовано.
const wallGap = 1

// wallCardHeight — сколько строк стены занимает карточка.
//
// Высота карточки на стене постоянна (две строки, см. renderCard), но мерять её
// всё равно приходится у самой отрисовки: «сколько карточек влезет в стену»
// перестаёт быть числом карточек уже при любой другой ширине окна, а зашивать
// сюда вторую формулу высоты значило бы завести две правды об одном.
//
// Это МЕРА карточки стены, а не всего окна прокрутки: сам алгоритм окна общий
// для всех списков (см. cardHeight) и меряет карточки той функцией, которую ему
// дали. Сообщения открытой переписки меряются иначе (zoomCardHeight), и это
// ровно то, ради чего алгоритм вынесен в общий.
func wallCardHeight(c card, width int, selected bool) int {
	return len(renderCard(c, width, selected))
}

// cardHeight — сколько строк занимает один элемент списка при заданной ширине и
// выделении.
//
// Списков, которые листаются окном прокрутки, два, и меряются они по-разному:
// карточка стены всегда двухстрочная (wallCardHeight), а блок сообщения в
// открытой переписке — своей высоты, по числу строк перенесённого текста
// (zoomCardHeight). Сам алгоритм окна (clampScrollToCursor и соседние) у них
// один и тот же и измеряет элементы этой функцией: заводить рядом вторую копию
// алгоритма «ради другой высоты карточки» значило бы через месяц получить два
// окна прокрутки, которые чинят одно и то же по-разному.
type cardHeight func(item card, width int, selected bool) int

// cardStep — строки, которые список занимает на элементе index, идущем после
// cards[index-1]: сам элемент и зазор перед ним. У первого элемента окна зазора
// сверху нет (он остался за пределами отрисовки), поэтому там стоимость на
// wallGap меньше.
func cardStep(measure cardHeight, cards []card, index, cursor, width int) int {
	return wallGap + measure(cards[index], width, index == cursor)
}

// clampWallScrollTop — окно прокрутки в границах стены: не выше самой старой
// карточки и не ниже самой новой. Те же границы, что у курсора, но отдельная
// функция: scrollTop и cursor — разные вещи, и путать их в одном имени значило бы
// потом искать, куда зажимается что.
func clampWallScrollTop(scrollTop, count int) int {
	return clampWallCursor(scrollTop, count)
}

// cardTotalRows — сколько строк экрана заняли бы ВСЕ элементы от from до конца
// списка, без обрезки по высоте (в отличие от отрисовки, которая обрезает
// хвост, если не влезло). Тем же способом счёта, что и весь остальной механизм
// окна (cardStep) — иначе посчитанное здесь разошлось бы с тем, что реально
// нарисуется.
func cardTotalRows(measure cardHeight, cards []card, from, cursor, width int) int {
	if from < 0 || from >= len(cards) {
		return 0
	}
	total := measure(cards[from], width, from == cursor)
	for index := from + 1; index < len(cards); index++ {
		total += cardStep(measure, cards, index, cursor, width)
	}
	return total
}

// backfillScrollTop — если ниже уже видимого окна остался пустой хвост экрана,
// а сверху есть ещё более старые карточки — окно подтягивает их вверх по одной,
// пока не заполнит экран целиком или не упрётся в самую старую карточку потока.
//
// Без этого шага (баг, пойманный человеком вживую: стрелка вверх с длинной
// развёрнутой карточки на короткую оставляла половину экрана пустой, хотя
// выше было что показать) clampScrollToCursor трогает scrollTop только когда
// курсор выходит ЗА окно — а свободное место внизу окна это не выход курсора
// за границы, и предыдущая логика такой случай не видела вовсе.
//
// На стене, где карточка всегда одной высоты, пустой хвост снизу больше не
// появляется — но механизм остаётся: карточки станут разной высоты на экране
// одного чата (задача 0155), и ловить этот баг заново не хочется.
// Шаг нужен спискам с элементами РАЗНОЙ высоты: сообщения открытой переписки
// как раз такие (одна строка или двадцать), и без добивки снизу у окна могла бы
// зиять дыра.
func backfillScrollTop(measure cardHeight, cards []card, scrollTop, cursor, width, height int) int {
	for scrollTop > 0 {
		candidate := scrollTop - 1
		if cardTotalRows(measure, cards, candidate, cursor, width) > height {
			break
		}
		scrollTop = candidate
	}
	return scrollTop
}

// scrollTopForCursor — самое верхнее окно, в котором выбранная карточка ещё
// попадает в кадр. Это ровно тот сдвиг, который нужен навигации: курсор ушёл ниже
// окна, и стена спускается ровно настолько, чтобы показать его первую строку, а не
// прыгает сразу на целый экран.
//
// Считается от курсора вверх, пока хватает высоты, — одним проходом и точно, тем
// же приёмом, что и у scrollTopToBottom (высота САМОЙ карточки-якоря — здесь
// курсора, там последней — идёт в used ПЕРВОЙ, до того как накапливать карточки
// над ней). Без этого (было найдено человеком вживую: развёрнуть длинную
// карточку внизу, уйти стрелкой вверх, вернуться стрелкой вниз — окно съезжало
// так, что от развёрнутой карточки было видно только две строки у самого низа
// экрана, а всё место наверху занимали старые короткие карточки) цикл шёл от
// used=0 и мерил только карточки НАД курсором, никогда не заглядывая в высоту
// самого курсора — из-за этого для очень высокой развёрнутой карточки окно
// уезжало на много карточек назад, вместо того чтобы остаться на ней самой.
//
// Высоты разной на стене больше не бывает (карточка всегда две строки), но сам
// приём остаётся: экран одного чата (задача 0155) вернёт сообщения разной
// высоты, и мерить окно по ним придётся снова.
func scrollTopForCursor(measure cardHeight, cards []card, cursor, width, height int) int {
	if cursor < 0 || cursor >= len(cards) {
		return clampWallCursor(cursor, len(cards))
	}
	cursorHeight := measure(cards[cursor], width, true)
	from := cursor
	used := cursorHeight
	for from > 0 && used < height {
		step := cardStep(measure, cards, from-1, cursor, width)
		// used+step — высота всего блока от from-1, и условие «> height» значит
		// ровно одно: блок не влезает, лезть выше нельзя. Раньше здесь стояло
		// «used+step-cursorHeight >= height» — с вычитанием высоты якорной
		// карточки, и оно было правильно ТОЛЬКО пока карточка занимала одну
		// строку: с двумя строками (задача 0156) оно разрешало блок выше экрана на
		// cursorHeight-1 строк, то есть выбранная карточка показывалась без строки
		// с текстом сообщения. Форма «used+step > height» — та же самая, что в
		// scrollPageTop и backfillScrollTop, и она не завязана на высоту карточки.
		if used+step > height {
			break
		}
		used += step
		from--
	}
	return from
}

// scrollTopToBottom — окно, в котором последняя карточка стоит у нижнего края
// стены: самое свежее сообщение видно сразу при открытии, а не спрятано за
// экраном старых.
//
// Идём от последней карточки вверх, пока стена не наполнится. Окно настолько
// высоко, насколько позволяет стена, поэтому последняя карточка стоит как можно
// ниже; если карточек не хватает даже на целый экран, окно остаётся на самой
// старой — дописывать пустоту вниз нельзя, тогда последняя карточка уехала бы от
// нижнего края.
//
// Ни одна карточка в окне не обрезается: блок от from до последней обязан
// влезать целиком (см. условие в цикле). Цена этого — короткий пустой хвост под
// последней карточкой, когда высота стены не выражается суммой «карточка плюс
// зазор»: при двухстрочной карточке достижимые высоты содержимого — 2, 5, 8, …,
// и на стене в 25 строк влезает 23 строки карточек с зазорами, а оставшиеся 2
// строки остаются пустыми. Обрезать карточку вместо этого нельзя: renderWall
// режет хвост, и свежее сообщение лишилось бы второй строки.
func scrollTopToBottom(measure cardHeight, cards []card, cursor, width, height int) int {
	last := len(cards) - 1
	if last < 0 || width <= 0 || height <= 0 {
		return 0
	}
	lastHeight := measure(cards[last], width, last == cursor)
	from := last
	used := lastHeight
	for from > 0 && used < height {
		step := cardStep(measure, cards, from-1, cursor, width)
		// Та же форма, что в scrollTopForCursor, scrollPageTop и
		// backfillScrollTop: блок от from-1 обязан влезать целиком, иначе
		// renderWall обрежет его снизу и последняя карточка потеряет нижнюю
		// строку. С вычитанием lastHeight (как было до задачи 0156) условие
		// было верно только для однострочной карточки.
		if used+step > height {
			break
		}
		used += step
		from--
	}
	return from
}

// scrollPageTop — окно на страницу ниже (delta > 0) или выше (delta < 0).
//
// Страница — это высота зоны, а не число карточек: карточки могут быть разной
// высоты, и двенадцать узких на одном экране занимают совсем не то же место, что
// двенадцать широких. Шаг считается по строкам, тем же способом, что и всё
// остальное окно.
func scrollPageTop(measure cardHeight, cards []card, scrollTop, cursor, width, height, delta int) int {
	if len(cards) == 0 || width <= 0 || height <= 0 {
		return 0
	}
	top := clampWallScrollTop(scrollTop, len(cards))
	used := 0
	if delta >= 0 {
		// Вниз: у карточки, которая перестала быть первой в окне, сверху
		// появляется зазор, поэтому шаг — карточка плюс строка.
		for top+1 < len(cards) {
			step := cardStep(measure, cards, top, cursor, width)
			if used+step > height {
				break
			}
			used += step
			top++
		}
		return top
	}
	// Вверх — тот же шаг и по той же причине: карточка перестала быть первой в
	// окне и получила зазор сверху. Считать зазор только в одну сторону нельзя —
	// тогда страница вверх выходила бы систематически длиннее страницы вниз, и
	// вернуться нажатием PgDown на то же место было бы невозможно.
	for top > 0 {
		step := cardStep(measure, cards, top-1, cursor, width)
		if used+step > height {
			break
		}
		used += step
		top--
	}
	return top
}

// wrapVisible — нарезка текста по ширине с переносом по словам, с сохранением
// абзацев: настоящий перенос строки в исходном тексте (см. normalizeMessageText)
// остаётся границей строки в выводе, а перенос по словам работает уже ВНУТРИ
// каждого абзаца отдельно. Раньше strings.Fields сразу на всём тексте стирал
// эту границу — абзацы вроде «🟠Обновления» / «Поддерживает…» сливались в один
// сплошной поток слов, хотя в оригинальном сообщении шли отдельными строками.
func wrapVisible(text string, width int) []string {
	if width <= 0 {
		return nil
	}
	var lines []string
	for _, paragraph := range strings.Split(text, "\n") {
		lines = append(lines, wrapParagraph(paragraph, width)...)
	}
	return lines
}

// wrapParagraph — перенос ОДНОГО абзаца (без внутренних переносов строк) по
// словам. Слово длиннее строки режется принудительно, иначе оно вылезло бы за
// карточку. Пустой абзац — тоже строка (пустая), а не «ничего»: так сохраняется
// намеренный отступ между разделами исходного сообщения (например, две
// подряд идущие "\n\n" в оригинале).
func wrapParagraph(text string, width int) []string {
	lines := make([]string, 0, 2)
	current := ""
	for _, word := range strings.Fields(text) {
		candidate := word
		if current != "" {
			candidate = current + " " + word
		}
		if cellWidth(candidate) <= width {
			current = candidate
			continue
		}
		if current != "" {
			lines = append(lines, current)
			current = ""
		}
		for cellWidth(word) > width {
			cut := width
			for cut > 1 && cellWidth(word[:cut]) > width {
				cut--
			}
			// cut — байтовый индекс, а не число ячеек: многобайтовая руна
			// (кириллица, эмодзи) режется этим индексом пополам, если он
			// попадает внутрь неё, и word[:cut] превращается в невалидный
			// UTF-8 (найдено при ревью 0154 — до неё принудительный разрез
			// на стене не проходил вовсе, карточка была только развёрнутой
			// многострочной, а этот путь виден с задачи 0155). Сдвигаем
			// назад до границы руны — cut > 0, а не > 1: у однобайтовой
			// первой руны cut могло бы устоять на 1, но для настоящей
			// границы руны предел ниже не нужен, весь текст — валидный
			// UTF-8, начало руны всегда найдётся раньше нуля.
			for cut > 0 && !utf8.RuneStart(word[cut]) {
				cut--
			}
			if cut == 0 {
				// Первая руна сама шире width (например, широкий эмодзи на
				// однобайтовой ширине) — резать её пополам всё равно нельзя,
				// поэтому забираем её целиком, а не оставляем пустую строку.
				_, size := utf8.DecodeRuneInString(word)
				cut = size
			}
			lines = append(lines, word[:cut])
			word = word[cut:]
		}
		current = word
	}
	if current != "" {
		lines = append(lines, current)
	}
	if len(lines) == 0 {
		lines = append(lines, "")
	}
	return lines
}
