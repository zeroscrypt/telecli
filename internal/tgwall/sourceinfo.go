// Сведения об источнике на строке 1 — то, что освободилось после переезда
// времени в конец строки текста (задача 0163): у личного диалога статус
// собеседника, у группы и канала — число участников или подписчиков.
//
// Оба приходят из TDLib апдейтами и обновляются живьём (см. applyWallGroupCountUpdate
// и applyWallUserStatusUpdate в sourceinfo_live.go), поэтому форматирование
// чистое и детерминированное: проверяется подстановкой своего «сейчас», а не
// ожиданием нужного времени суток.

// timeNow — «сейчас» для относительных дат в статусе собеседника. Переменная,
// а не прямой вызов time.Now(), ровно по той же причине, по которой в этом
// проекте подменяются другие внешние часы: тест с реальным временем ловился бы
// о полуночи и о смене суток.
var timeNow = time.Now

// memberCountText — число участников или подписчиков компактной записью, как в
// самом Telegram: «999», «1,2K», «45K», «2,1M».
//
// Пороги и формат (задача 0163, косметика по прямому указанию человека — в
// отличие от счётчика непрочитанных у него потолка «99+» нет вовсе: у канала
// может быть и 200 тысяч подписчиков, и это осмысленное число, а не факт
// «много»):
//
//   - до 1000            — само число, без сокращения;
//   - от 1000 до 999999  — тысячи, «K»;
//   - от 1000000         — миллионы, «M».
//
// Один знак после запятой ставится только когда он что-то значит: 1000 — это
// «1K», а не «1,0K», и 2000 — «2K», а не «2,0K». При десяти и больше знак
// после запятой не ставится вовсе (45K, не 45,0K): дробная часть там уже
// ничего не различает, а колонка на строке заголовка дорогого стоит.
//
// Разделитель дробной части — запятая, как в самом Telegram на русском языке
// и как в остальном интерфейсе проекта.
//
// Ноль и отрицательное значение дают ПУСТУЮ строку, а не «0»: это «данных ещё
// нет» (апдейт не пришёл, или у чата нет счётчика), и ноль рядом с именем
// читался бы как «у канала ноль подписчиков».
func memberCountText(count int32) string {
	if count <= 0 {
		return ""
	}
	return compactCount(int64(count))
}

// compactCount — само сокращение числа. Отдельно от memberCountText, потому что
// это единственное место, где живут и пороги, и округление, а memberCountText
// отвечает за то, что при нуле показывается ничего.
func compactCount(value int64) string {
	switch {
	case value >= 1_000_000:
		return compactUnit(value, 1_000_000, "M")
	case value >= 1000:
		return compactUnit(value, 1000, "K")
	default:
		return strconv.FormatInt(value, 10)
	}
}

// compactUnit — «12 345» при unit=1000 → «12K», при 1 234 000 → «1,2M».
//
// mantissa — значение, делённое на единицу: 12.345 или 1.234. Знак после
// запятой печатается, только если дробная часть после округления до одного
// знака не нулевая, иначе он был бы пустым шумом в колонке заголовка.
//
// Отдельно проверяется случай, когда округление УВЕЛИЧИВАЕТ мантиссу до самой
// единицы: 999 999 при unit=1000 дал бы «1000K», что читается хуже, чем
// «1M», поэтому значение переезжает в следующую единицу.
func compactUnit(value, unit int64, suffix string) string {
	mantissa := float64(value) / float64(unit)
	rounded := math.Round(mantissa*10) / 10
	// 999.999K → 1000K → 1M: округление вынесло число за пределы единицы.
	if rounded >= 1000 {
		return "1" + nextUnitSuffix(suffix)
	}
	if rounded == math.Trunc(rounded) {
		return strconv.FormatFloat(rounded, 'f', 0, 64) + suffix
	}
	// Форматируется через fmt, а не strconv: разделителем дробной части в Go
	// по умолчанию точка, а нужен запятой (см. комментарий у memberCountText).
	return strings.Replace(fmt.Sprintf("%.1f", rounded), ".", ",", 1) + suffix
}

// nextUnitSuffix — суффикс следующей по величине единицы: у тысяч миллионы, у
// миллионов — десятки миллионов, которого счётчик участников не достигает, но
// функция не должна ошибаться и на нём.
func nextUnitSuffix(suffix string) string {
	if suffix == "K" {
		return "M"
	}
	return "B"
}

// userStatusText — статус собеседника по-русски, в бакетах мессенджеров
// (задача 0163). Границы бакетов приблизительные и будут уточнены человеком по
// живому виду — точное воспроизведение всех границ Telegram здесь не
// требуется и не окупается.
//
//	userStatusOnline     → «в сети»
//	userStatusOffline    → «недавно» / «сегодня в 13:04» / «вчера в 13:04»
//	                       / «15.09» / «15.09.2025»
//	userStatusRecently   → «был(а) недавно»
//	userStatusLastWeek   → «был(а) на этой неделе»
//	userStatusLastMonth  → «был(а) в этом месяце»
//	userStatusEmpty      → пусто: показывать нечего
//
// «был(а)» — с «(а)», а не с угаданным родом: пола у нас нет, а ошибиться в
// этом заметно хуже, чем написать нейтральную форму.
//
// Пустая строка (userStatusEmpty, приватность, заблокированный аккаунт, данные
// ещё не пришли) — это НЕ пустая заглушка на экране: такую карточку сведениями
// не занимаются вовсе, имя стоит там же, где у карточек со статусом, и лишнего
// зазора после него не появляется (см. cardTitleInfo и renderWallCard).
func userStatusText(status auth.UserStatus, now time.Time) string {
	switch status.Kind {
	case auth.UserStatusOnline:
		return "в сети"
	case auth.UserStatusOffline:
		return userLastSeenText(status.WasOnline, now)
	case auth.UserStatusRecently:
		return "был(а) недавно"
	case auth.UserStatusLastWeek:
		return "был(а) на этой неделе"
	case auth.UserStatusLastMonth:
		return "был(а) в этом месяце"
	default:
		return ""
	}
}

// userLastSeenText — «когда выходил» по времени выхода из сети. Отдельная
// функция, потому что только у userStatusOffline есть точное время, и все
// границы бакетов относятся к нему одному.
//
// Пороги: до часа — «недавно»; сегодня — «сегодня в HH:MM»; вчера — «вчера в
// HH:MM»; до конца года — «ДД.ММ»; дальше — «ДД.ММ.ГГГГ». Год в сокращении не
// пишется, пока он текущий, — «15.09» читается однозначно внутри года, который
// человек знает.
//
// now передаётся параметром, а не берётся из timeNow внутри: у этой функции
// чистая арифметика по двум моментам времени, и подставлять «сейчас» должен
// вызывающий (cardTitleInfo), а не она сама.
func userLastSeenText(wasOnline int64, now time.Time) string {
	// was_online <= 0 бывает только на битом объекте (см. ParseUserStatus).
	// Показывать «1970 в 00:00» нельзя, а молчать тоже нельзя — статус-то
	// «вышел из сети» есть, — поэтому общий для всех бакетов «был(а) недавно».
	if wasOnline <= 0 {
		return "был(а) недавно"
	}
	then := time.Unix(wasOnline, 0).Local()
	now = now.Local()
	switch {
	case now.Sub(then) < time.Hour:
		return "недавно"
	case then.YearDay() == now.YearDay() && then.Year() == now.Year():
		return "сегодня в " + then.Format("15:04")
	case isYesterday(then, now):
		return "вчера в " + then.Format("15:04")
	case then.Year() == now.Year():
		return then.Format("02.01")
	default:
		return then.Format("02.01.2006")
	}
}

// isYesterday — вчера ли это. Отдельная функция, а не «минус сутки», потому что
// сравнение с «now минус 24 часа» ломается ровно на границе суток: ночью на
// час сутки отстаёт не вчерашнее число, а позавчерашнее.
func isYesterday(then, now time.Time) bool {
	yesterday := now.AddDate(0, 0, -1)
	return then.Year() == yesterday.Year() &&
		then.YearDay() == yesterday.YearDay()
}
