// Package tgwall — стена: единая лента сообщений из каналов, чатов и личных
// диалогов. Отдельный бинарь рядом с tgcli, на тех же библиотеках, но со своей
// палитрой и своей вёрсткой.
//
// В этой первой версии стена не подключена к Telegram: карточки зашиты в код,
// как в макете. Подключение TDLib — отдельная задача.
package tgwall

import "charm.land/lipgloss/v2"

// Палитра стены — буквально значения из макета «tgwall — мокап новой стены».
// Ничего не подбирается на глаз: человек утвердил макет целиком, и палитра здесь
// ровно та, что в нём.
var (
	// Фоны: основной — под стеной и полями вокруг карточек (обычная карточка с
	// ним сливается — тип виден по цвету левой границы, не по отдельному боксу),
	// панель — под полем ввода, выделение — под выбранной карточкой стены
	// (единственный признак выбора: карточка стены всегда одной высоты — две
	// строки, см. renderCard). Значения подобраны и подтверждены человеком по
	// живой проверке в реальном терминале, не из исходного макета: сначала
	// #333333 (первая версия — #141414/#1e1e1e оказались недостаточно
	// заметны), затем затемнено до #222222 (2026-09-30, вживую оказалось
	// светлее, чем хотелось), затем осветлено обратно до #333333 (2026-09-30,
	// тот же день, вместе с уходом от разноцветных границ у всех карточек к
	// единому правилу «акцент только у выделенной» — приглушённые остальные
	// карточки стали не так заметны, светлее выделение снова понадобилось).
	PaletteBackgroundMain     = lipgloss.Color("#111111")
	PaletteBackgroundPanel    = lipgloss.Color("#1e1e1e")
	PaletteBackgroundSelected = lipgloss.Color("#333333")

	// PalettePanelBorder — рамка панели переписки, когда в ней НЕТ фокуса:
	// тёмно-серая #252525, заметная ровно настолько, чтобы панель читалась как
	// отдельная колонка, но не спорила с акцентом типа чата в фокусе. С фокусом
	// рамка красится акцентом открытого чата (см. panelAccent) — то есть «здесь
	// я» и «это граница чата» видны по одному и тому же знаку (значения
	// человека, 2026-10-01).
	PalettePanelBorder = lipgloss.Color("#252525")

	// Границы: разделители между зонами экрана.
	//
	// Второй, более яркий цвет границы (PaletteBorderStrong) удалён: после
	// задачи 0156 вертикальная черта внутри карточки красится акцентным цветом
	// источника, и к этому моменту в коде не осталось ни одного обращения к
	// старому цвету (проверено поиском по всему репозиторию, задача 0159).
	PaletteBorder = lipgloss.Color("#3c3c3c")

	// Текст: обычный, приглушённый (время и теги) и еле заметный (строка
	// подсказок под стеной и заглушка «Чатов нет»). Три значения зафиксированы
	// человеком явно (2026-09-30): dddddd/888888/555555, не производные друг
	// от друга — менять только по его слову.
	PaletteText      = lipgloss.Color("#dddddd")
	PaletteTextMuted = lipgloss.Color("#888888")
	PaletteTextFaint = lipgloss.Color("#555555")

	// Цвет СЛОВ в строке подсказок под полем. Отдельное значение, а не
	// PaletteTextFaint: в подсказке две разные вещи — сами сочетания клавиш и
	// слова-подписи к ним, — и человек попросил видеть их по-разному
	// (2026-10-01): сочетания #888888, слова #666666. С PaletteTextFaint (#555555)
	// слова были бы не темнотой, а просто частью общей серости строки, и глаз не
	// находил бы в подсказке главного — что нажимать.
	PaletteHintWord = lipgloss.Color("#666666")

	// Цвет СОЧЕТАНИЙ клавиш в строке подсказок. Отдельное значение, а не
	// PaletteTextMuted (#888888): тем же цветом нарисованные время карточек и
	// теги типа потеряли бы смысл подсказки — «что нажимать» перестало бы
	// отличаться от серости остального текста. Значение задано человеком
	// (2026-10-02) и светлее прежнего #888888.
	PaletteHintKey = lipgloss.Color("#999999")

	// Цвета по типу источника: левая граница карточки и точка у тега справа.
	//
	// Канал остался синим, а чат и личный поменялись местами по велению человека
	// (2026-09-30, задача 0166): чат — тёплый оранжевый, личный — зелёный. Значения
	// именно такие, а не «похожие оттенки»: человек выбрал их сам, и подбирать
	// рядом с ними другие значило бы разойтись с его выбором. Меняются только эти
	// два значения — все места, где они рисуются (граница карточки, точка у тега,
	// счётчик в заголовке, галка меню фильтра, граница поля ввода), берут их отсюда
	// и перекрашиваются вместе, отдельно ничего подстраивать не нужно.
	PaletteChannel  = lipgloss.Color("#5c9cf5")
	PaletteChat     = lipgloss.Color("#E99B79")
	PalettePersonal = lipgloss.Color("#1A7C33")

	// Зелёный спиннера нижней строки.
	PaletteOK = lipgloss.Color("#7fd88f")

	// Смысловая подсветка текста сообщения: ссылки, @упоминания, #теги,
	// /команды, английские слова и числа красятся отдельно от обычного текста
	// (см. highlight.go). Те же значения, что в internal/tgclitui (по прямому
	// указанию человека — «как было раньше»), а не подобраны заново: смысл в
	// переносе уже проверенного вида, а не в новой палитре.
	PaletteTextURL     = lipgloss.Color("#89B4FA")
	PaletteTextMention = lipgloss.Color("#F5C2E7")
	PaletteTextTag     = lipgloss.Color("#F9E2AF")
	PaletteTextCommand = lipgloss.Color("#CBA6F7")
	PaletteTextNumber  = lipgloss.Color("#FAB387")
	PaletteTextEnglish = lipgloss.Color("#A6E3A1")
)
