// activeWidthMethod — метод подсчёта ширины ячеек, СОГЛАСОВАННЫЙ с реальным
// терминалом (см. case tea.ModeReportMsg в Update). Значение по умолчанию —
// ansi.WcWidth, то же самое, с которым стартует и сам renderer bubbletea
// (ultraviolet.NewScreenBuffer: "Method: ansi.WcWidth", подтверждено чтением
// исходников — не догадка): пока терминал не подтвердил поддержку Unicode-
// режима DEC 2027, bubbletea меряет ширину по старому, посимвольному счёту, и
// наша вёрстка обязана делать то же самое, иначе она и настоящий рендер
// разойдутся ровно на символах вроде «ℹ️» — что и произошло, найдено человеком
// вживую.
//
// Пакетная переменная, а не поле Model: согласование происходит один раз на
// весь процесс, задолго до первого кадра, а функции вёрстки (fitLine,
// truncateVisible, wrapVisible, wallCardHeight и т.д.) — свободные, не методы
// Model, и протаскивать через них состояние ради одного этого значения
// значило бы переписать всю вёрстку.
// defaultWidthMethod — вынесен в отдельную константу (не просто литерал внутри
// activeWidthMethod), чтобы тест на сам факт «дефолт — WcWidth» не зависел от
// порядка выполнения тестов: activeWidthMethod — общая для пакета переменная,
// и тест, проверяющий её напрямую после того, как другой тест её поменял (а
// восстановление порядка Go не гарантирует), проверял бы чужое состояние, а
// не объявленное значение по умолчанию.
const defaultWidthMethod = ansi.WcWidth

var activeWidthMethod = defaultWidthMethod

// cellWidth — ширина строки в ячейках терминала ТЕМ методом, что реально
// согласован с терминалом (activeWidthMethod). Используется везде в этом
// пакете вместо голого lipgloss.Width — тот всегда считает по GraphemeWidth,
// независимо от того, что на самом деле подтвердил терминал.
func cellWidth(s string) int {
	return activeWidthMethod.StringWidth(s)
}

// errNoTDLibClient — клиента TDLib нет: модель собрана без него (тест) или он
// не подключился. Одна ошибка на все команды стены вместо четырёх одинаковых
// errors.New в четырёх файлах: различие между ними ничего не значит, а
// одинаковые строки в разных местах разъезжаются при первой же правке
// формулировки.
var errNoTDLibClient = errors.New("TDLib client is nil")

// ellipsis — многоточие обрезки. Одна константа на все места, где обрезанный
// текст помечается многоточием: truncateVisible, «продолжение» в конце первой
// строки карточки (collapsedText) и превью в модалке удаления. Это один и тот же
// знак, и разъехаться они не должны.
const ellipsis = "…"

// Строки экрана под стеной, которые нельзя урезать: разделитель над блоком ввода,
// строка подсказок, разделитель под ним и нижняя строка. Само поле растёт вверх и
// забирает остаток.
const wallReservedRows = 4

// Строки экрана, которые каркас занимает вокруг стены: строка фильтра и название
// открытой переписки вверху и строка временных системных сообщений между стеной и
// блоком ввода.
//
// Отдельными константами, а не добавкой к wallReservedRows: у той свой смысл —
// «строки ПОД стеной», и смешав с ней эти две, через полгода никто не вспомнил бы,
// какие из них где считаются. В формуле высоты стены они стоят вместе с той
// константой: стена обязана уживаться с обеими сторонами экрана сразу, а не по
// очереди.
const (
	wallTopBarRows = 1
	wallNoticeRows = 1
)

// Model — стена: список карточек, курсор по ним, поле ввода и кадр спиннера.
type Model struct {
	// ctx и client — для начальной загрузки (см. wallLoadedCmd). Живут в модели,
	// а не передаются в команду параметрами, потому что команда живёт дольше
	// вызова New: она исполняется уже во время работы программы.
	ctx    context.Context
	client auth.TDClientInterface
	// username — собственный ник аккаунта для нижней строки. Пустая строка —
	// у аккаунта нет ника, и тогда рядом с лого не показывается ничего.
	username string
	// appName и version — то, как приложение называет себя и какой у него
	// релиз. Оба приходят из точки входа (cmd/telecli): версия выставляется
	// при сборке через -ldflags "-X main.version=vX.Y.Z", а название живёт
	// там же, потому что бинарник зовут telecli, и стене его имя известно не
	// лучше, чем кому-то ещё в проекте. Здесь только отрисовка, своего
	// источника у этих строк нет и быть не должно.
	appName string
	version string
	// loading — идёт ли сейчас загрузка стены целиком. Пока она не закончилась,
	// карточек на стене нет и спиннер в нижней строке крутится. Это
	// настоящее состояние, а не «всегда грузится» из каркаса: пустая стена с
	// крутящимся спиннером после загрузки читалась бы как «идёт» даже когда
	// данные уже пришли. Загрузка истории открытой переписки сюда НЕ входит —
	// у неё своё поле (zoom.loading), а для индикатора обе объединяет
	// isLoading.
	loading bool
	// loadError — чем загрузка сорвалась целиком (список чатов не пришёл).
	// Отдельное поле, а не карточка в стене: сообщение об ошибке не должно
	// занимать место среди сообщений и выглядеть как чужое сообщение в потоке.
	loadError string

	cards  []card
	cursor int
	// source — полный поток карточек, БЕЗ фильтра: снимок плюс живые апдейты.
	// cards — то, что стена показывает, то есть source, пропущенный через
	// текущий фильтр (см. filterCards).
	//
	// Два среза нужны потому, что фильтр меняется на ходу, а живой апдейт
	// приходит в любой момент: пересобирать cards из source — единственный
	// способ не потерять и не размножить карточки, и единственный, при котором
	// живой предпросмотр («переключил галку — стена перефильтровалась сразу»)
	// получается сам собой. Всё остальное в пакете работает с cards и потому не
	// знает про фильтр вовсе: курсор, окно прокрутки, цель ответа и открытая
	// переписка работают с тем, что человек видит.
	//
	// Правило одно и обязательное: любая правка потока идёт в source, а cards
	// после неё пересобирается (rebuildVisible). Правка карточки на месте с
	// забытой пересборкой оставила бы два среза расходящимися, и галка «Новое
	// сообщение» поехала бы.
	source []card
	// filter — что человек выбрал показывать (см. filter.go).
	filter wallFilter
	// folders — папки человека, как их прислал TDLib. Нужны меню фильтра;
	// порядок сохраняется тот, что задал человек в Telegram.
	folders []auth.Folder
	// chatFolders — какие папки содержат какой чат. Приходит отдельным запросом
	// (см. folders.go), потому что в объекте chat папок нет.
	chatFolders chatFolderIDs
	// filterMenu — открытое меню фильтра, nil — меню на экране нет (см.
	// filtermenu.go).
	filterMenu *wallFilterMenu
	// chatsByID — чаты последнего снимка по id. Нужны, чтобы из живого апдейта
	// (который приносит только сообщение) собрать карточку: без чата у неё не
	// было бы ни заголовка, ни типа, ни тега. Карта строится из wallLoadedMsg
	// целиком и не пополняется по ходу работы: чат, появившийся после старта, —
	// отдельная задача (в tgclitui это целый блок «Живость списка чатов»).
	chatsByID map[int64]auth.Chat
	// groupMemberCounts и userStatuses — живые сведения об источниках по id
	// объекта из типа чата (auth.Chat.PeerID): число участников у групп и
	// каналов, статус у личных диалогов. Кэши, а не поля карточек напрямую,
	// потому что апдейт TDLib может прийти ДО того, как карточка этого источника
	// построена (TDLib шлёт их по всем чатам аккаунта уже на загрузке списка),
	// и тогда значение обязано пережить отсутствие карточки и подхватиться ею
	// позже — единственное место, где это происходит, syncWallSourceInfo.
	groupMemberCounts map[int64]int32
	userStatuses      map[int64]auth.UserStatus
	// scrollTop — индекс первой карточки, с которой стена рисуется. Без этого
	// окна стена всегда показывала поток с самой старой карточки, и при сотнях
	// чатов самое свежее сообщение было за пределами экрана: стена выглядела
	// «застрявшей» на древнем конце.
	scrollTop int

	input     *textarea.Model
	inputRows int
	// replyTarget — ответ на карточку, выбранную по Ctrl+R (nil — ответа нет).
	// Живёт отдельно от значения поля: строка «на что отвечаем» рисуется над полем
	// сама по себе, и вводить её настоящим текстом значило бы отправлять её вместе
	// с сообщением.
	replyTarget *replyTarget

	// showConfirm и три поля рядом — открытая модалка подтверждения удаления и
	// то, что в ней подтверждается. Живут отдельными полями, а не снимком
	// карточки: карточка уходит из потока (и сменяется новой, когда тот же чат
	// пришлёт своё), а удалять надо ровно то сообщение, которое человек видел в
	// вопросе. Вопрос с превью готовится один раз при открытии (confirmPrompt) —
	// иначе он поехал бы за курсором.
	showConfirm      bool
	confirmChatID    int64
	confirmMessageID int64
	confirmPrompt    string

	// frame — кадр спиннера нижней строки.
	frame int

	// notice — временное системное сообщение в строке между стеной и вводом,
	// nil — строка пустая (занимает место вовсе, см. renderSystemNotice).
	//
	// Заполняется только через ShowSystemNotice: там же живут счётчик версий
	// noticeID и таймер гашения, и писать в это поле мимо метода нельзя —
	// сообщение без таймера висело бы на экране вечно.
	notice *wallSystemNotice
	// noticeID — счётчик версий сообщения. Живёт на модели, а не внутри
	// wallSystemNotice, по той же причине, что и zoomLoadID: внутри структуры он
	// обнулялся бы вместе с каждым новым сообщением, и таймер, заведённый для
	// предыдущего, снова совпал бы по номеру и погасил бы свежее сообщение.
	noticeID int

	// zoom — открытая переписка одного источника, nil — переписки на экране нет
	// (ни панели справа, ни полноэкранного окна). Подробнее — в zoom.go.
	zoom *wallZoom
	// zoomLoadID — счётчик попыток загрузки переписки. Живёт на модели, а не
	// внутри wallZoom, и растёт монотонно за всю жизнь программы: внутри
	// структуры он обнулялся бы при каждом новом wallZoom, и повторное открытие
	// того же источника начиналось бы с того же номера, что и предыдущее, —
	// устаревший ответ применился бы поверх текущего состояния (см.
	// applyWallZoomLoaded).
	zoomLoadID uint64
	// zoomFocused — фокус на переписке, а не на списке. Смысленно только в
	// широком режиме при открытом zoom: в узком переписка занимает весь ввод и
	// отдельного фокуса не существует, в широком по умолчанию фокус на списке.
	// Переключается Tab (см. zoomHasFocus — единое условие «смотрим в переписку»).
	zoomFocused bool

	// previewPanel — какая из панелей переписки СВОБОДНА, то есть следует за
	// курсором стены; вторая в это время держит зафиксированный чат.
	//
	// В ДВУХПАНЕЛЬНОМ режиме Enter на ленте МЕНЯЕТ их местами (переключает
	// свободную панель), а не открывает чат в следующей по кругу. Значение имеет
	// смысл только при двух панелях: при одной панели свободна она всегда, и
	// вся эта логика выключена (см. syncWallZoomToCursor).
	previewPanel wallPanel

	// zoomPinned — переписка второй панели (panelChat2), закреплённая
	// клавишами Ctrl+1/Ctrl+2 и Enter'ом из ленты. В отличие от m.zoom она НЕ
	// едет за курсором стены: это решение человека (2026-10-01), и без него
	// первое же движение стрелкой по ленте тихо переставило бы закреплённый
	// чат на другой.
	//
	// nil — вторая панель пуста, и в трёхколоночном режиме на её месте фон.
	zoomPinned *wallZoom

	// focusPanel — где сейчас фокус: панель 0 (лента), 1 или 2. Число, а не
	// флаг, потому что панелей переписки стало две, и «фокус не на переписке»
	// больше не различает «на ленте» и «на второй панели».
	//
	// Заменяет прежний zoomFocused; в узком режиме игнорируется — там
	// переписка занимает весь ввод и отдельного фокуса нет (см. zoomHasFocus).
	focusPanel wallPanel

	// keymap — раскладка клавиш поверх конфигурации (keybindings.toml, секция
	// [tgwall]). Поведение и подсказки берутся отсюда обе, поэтому они не могут
	// разойтись между собой (см. keymap.go).
	keymap keyMap

	width  int
	height int
}

// isLoading — грузится ли сейчас что-то, что человек видит на экране: сама
// стена (m.loading) ИЛИ история открытой переписки (m.zoom.loading).
//
// Единое место решения, а не размазанная по отрисовке проверка: у индикатора
// один потребитель, но источников загрузки два, и проверка только первого из
// них молча показывала пустоту всё то время, пока шла история переписки —
// выглядело это как «ничего не происходит» (найдено человеком вживую).
func (m Model) isLoading() bool {
	return m.loading || (m.zoom != nil && m.zoom.loading)
}

// New — модель стены. Карточек в ней пока нет: сначала показывается пустая стена
// со спиннером, а данные приезжают командой из Init() (см. wallLoadedCmd).
// Ожидание сети на запуске программы блокировало бы и ввод, и отрисовку, поэтому
// загрузка идёт в фоне, как и весь остальной TUI.
//
// keys — раскладка клавиш из конфигурации, передаётся снаружи, а не читается
// внутри: чтение файла умеет ошибаться, а New не возвращает ошибку (см. ровно так
// же устроен tgcli).
//
// settings — настройки из settings.toml, откуда берётся сохранённый фильтр
// источников (см. config.WallFilter). Настройки, а не готовый фильтр: держать
// внутренний тип стены в сигнатуре New значило бы заставлять пакет config знать
// про internal/tgwall, а тот наоборот знает про config.
//
// appName и version — имя и версия приложения для нижней строки (см. Model).
// Рядом с settings, а не внутри него: одно — про файлы настроек, другое — про
// то, чем собран этот конкретный запуск, и смешивать их в одной структуре
// значило бы тащить версию в конфигурацию, где её быть не должно.
func New(ctx context.Context, client auth.TDClientInterface, username string, keys config.TgwallKeyBindings, settings config.Settings, appName, version string) Model {
	if ctx == nil {
		ctx = context.Background()
	}
	input := newInput()
	m := Model{
		ctx:      ctx,
		client:   client,
		username: username,
		appName:  appName,
		version:  version,
		loading:  true,
		input:    &input,
		keymap:   keyMap{keys: keys},
		filter:   wallFilterFromSettings(settings.WallFilter),
	}
	m.applyLayout()
	return m
}

func (m Model) Init() tea.Cmd {
	load := m.wallLoadedCmd()
	live := m.waitForWallMessageUpdate()
	unread := m.waitForWallUnreadUpdate()
	// Живые сведения об источнике (число участников и статус собеседника).
	// Подписка ровно та же и ровно с тем же обоснованием, что у остальных
	// живых каналов выше: TDLib шлёт эти апдейты сам при загрузке списка чатов
	// (проверено вживью на настоящем аккаунте, задача 0163), поэтому снимок
	// значений не нужно ни запрашивать, ни ждать отдельного запроса.
	groupCounts := m.waitForWallGroupCountUpdate()
	userStatuses := m.waitForWallUserStatusUpdate()
	userProfiles := m.waitForWallUserProfileUpdate()
	// Подписка на папки — с самого старта, а не по первому нажатию ctrl+p: список
	// папок нужен и для сохранённого фильтра (отмеченная папка без её состава
	// молча скрыла бы все её чаты), и для самого меню.
	folders := m.waitForWallFoldersUpdate()
	// Живые удаления (задача 0165): без подписки удалённое сообщение висело бы в
	// открытой переписке и на карточке источника до перезапуска приложения.
	deleted := m.waitForWallDeleteUpdate()
	if m.input == nil {
		return tea.Batch(load, live, unread, groupCounts, userStatuses, userProfiles, folders, deleted, spinnerTickCmd())
	}
	return tea.Batch(m.input.Focus(), spinnerTickCmd(), load, live, unread,
		groupCounts, userStatuses, userProfiles, folders, deleted)
}

func (m Model) Update(msg tea.Msg) (tea.Model, tea.Cmd) {
	switch msg := msg.(type) {
	case tea.ModeReportMsg:
		// bubbletea сам спрашивает терминал при старте, поддерживает ли он
		// Unicode-режим DEC 2027 (посимвольная группировка графемных кластеров),
		// и результат этого же запроса шлёт и в Update() модели, не только себе.
		// Ловим его здесь, чтобы cellWidth считал ширину ТЕМ ЖЕ методом, что
		// реально использует терминал (см. activeWidthMethod) — иначе наша
		// вёрстка и настоящий рендер терминала расходятся на символах вроде
		// «ℹ️» (найдено человеком вживую: правая часть строки съезжала на одну
		// ячейку).
		if msg.Mode == ansi.ModeUnicodeCore {
			switch msg.Value {
			case ansi.ModeSet, ansi.ModeReset, ansi.ModePermanentlySet:
				activeWidthMethod = ansi.GraphemeWidth
			}
		}
		return m, nil
	case tea.WindowSizeMsg:
		m.width = max(0, msg.Width)
		m.height = max(0, msg.Height)
		m.applyLayout()
		// Окно прокрутки пересчитывается под новый размер терминала: при
		// уменьшении окна выбранная карточка ушла бы за нижний край, и на экране
		// не осталось бы ни одной выбранной карточки вообще. Размеры — те, по
		// которым стена реально рисуется: в широком режиме это суженная колонка и
		// высота содержимого панели, а не весь терминал (см. wallColumnWidth и
		// wallContentHeight).
		m.scrollTop = clampScrollToCursor(wallCardHeight, m.cards, m.scrollTop, m.cursor, m.wallColumnWidth(), m.wallContentHeight())
		if m.zoom != nil {
			m.zoom.scrollTop = clampScrollToCursor(zoomCardHeight, m.zoomCardsOf(m.zoom, m.zoom.messages), m.zoom.scrollTop, m.zoom.cursor, m.zoomListWidth(), m.wallZoomListHeight())
		}
		// Сжатие ниже трёхколоночного порога закрывает ВТОРУЮ переписку начисто
		// (решение человека, 2026-10-01): держать её в памяти «на потом» — значит
		// держать подписку на живые апдейты вхолостую и ждать отклика TDLib,
		// которого на экране нет. Вернётся ли панель после расширения окна — нет,
		// откроет её следующий Enter или Ctrl+2.
		if !m.wallTwoPanelMode() {
			m.zoomPinned = nil
		} else {
			// Вход в двухпанельный режим: по умолчанию свободна первая панель.
			if !m.previewPanel.isChatPanel() {
				m.previewPanel = panelChat1
			}
		}
		// Расширение терминала за узкий порог открывает панель переписки ровно
		// один раз, на этом ресайзе: без этого шага переписка появилась бы только
		// после следующего движения курсором, а первый широкий кадр был бы пустой
		// панелью.
		return m.syncWallZoomToCursor()
	case wallLoadedMsg:
		m.loading = false
		m.loadError = ""
		// Состав чатов нужен всем следующим живым апдейтам, поэтому обновляется
		// на каждом приходе, а не только на первом: отдельный случай ради
		// повторного снимка здесь не нужен. Чтение из пустой карты безопасно —
		// апдейт по неизвестному чату молча отбросится.
		m.chatsByID = chatsByID(msg.chats)
		// Повторный приход не сбрасывает ни курсор, ни окно: стена уже загружена,
		// человек по ней листает, и каждый новый снимок возвращал бы его на самое
		// начало потока. Живые апдейты этот путь не задевают: карточка из
		// updateNewMessage уходит в поток через applyWallMessageUpdate, а не
		// переживает повторный снимок (тот заменяет поток целиком — на практике
		// снимок приходит один раз, из Init).
		//
		// followLatest только для первой загрузки: стена отсортирована по
		// возрастанию даты (старые сверху), и при сотнях чатов последняя карточка
		// за пределами экрана — курсор стоял бы на невидимом сообщении, и одно
		// нажатие ↑ уводило бы его через весь поток. Широкий терминал: переписка
		// источника под курсором открывается сразу после загрузки стены, без
		// всякого Enter, — иначе первый кадр широкого экрана показывал бы пустую
		// панель.
		followLatest := len(m.cards) == 0
		m.source = msg.cards
		// Снимок источника мог прийти ДО живых апдейтов (TDLib шлёт их по всем
		// чатам аккаунта параллельно с загрузкой списка), и тогда значения уже
		// лежат в кэшах, а source их ещё не знает. Наводим source на кэши ДО
		// rebuildVisible: тот выводит m.cards из m.source через filterCards, и
		// сведения обязаны быть в source к этому моменту, иначе первый кадр
		// показал бы карточки без счётчика/статуса до следующего живого апдейта.
		m = m.syncWallSourceInfo()
		m = m.rebuildVisible(followLatest)
		if followLatest {
			// Первый запуск: открыть в панелях столько последних чатов, сколько
			// панелей есть (решение человека, 2026-10-01 — «если место позволяет
			// только 1, то последний в списке; если позволяет, то последних два»).
			//
			// Именно первый запуск: при повторном снимке переписки уже открыты те,
			// что человек выбрал сам, и открывать ещё и последние значило бы
			// перебивать его выбор.
			if m.wallTwoPanelMode() {
				m.previewPanel = panelChat1
			}
			next, cmd := m.openLatestChats()
			m = next
			return m, cmd
		}
		return m.syncWallZoomToCursor()
	case wallLoadedErrorMsg:
		m.loading = false
		m.loadError = msg.err.Error()
		return m, nil
	case wallZoomLoadedMsg:
		// Ответ на запрос истории переписки. Сверку источника и номера попытки
		// делает applyWallZoomLoaded: устаревший ответ обязан быть отброшен
		// молча.
		return m.applyWallZoomLoaded(msg), nil
	case wallMessageUpdateMsg:
		// Три исхода, тот же контракт, что у живых сообщений ленты tgcli: закрытый
		// канал восстанавливать нечем и незачем, нераспознанный апдейт молча
		// пропускается с переподпиской, годное сообщение идёт в поток.
		if msg.closed {
			return m, nil
		}
		if !msg.valid {
			return m, m.waitForWallMessageUpdate()
		}
		m = m.applyWallMessageUpdate(msg.chatID, msg.message)
		// То же сообщение попадает и в открытую переписку, если открыта именно
		// его: карточка стены и список переписки рисуются из разных источников,
		// и без этого шага сообщение в открытом чате не появлялось бы на экране.
		m.insertWallZoomMessage(msg.chatID, msg.message)
		// Перестановка карточек стены могла увести курсор на другой источник — в
		// широком режиме тогда обязана смениться и переписка (syncWallZoomToCursor
		// молчит, если источник тот же, и сеть зря не дёргается).
		m, zoom := m.syncWallZoomToCursor()
		return m, tea.Batch(m.waitForWallMessageUpdate(), zoom)
	case wallUnreadUpdateMsg:
		// Тот же трёхвариантный контракт, что у живых сообщений: закрытый
		// канал восстанавливать нечем, нераспознанный апдейт пропускается с
		// переподпиской, годный меняет только число.
		if msg.closed {
			return m, nil
		}
		if !msg.valid {
			return m, m.waitForWallUnreadUpdate()
		}
		m = m.applyWallUnreadUpdate(msg.chatID, msg.unreadCount)
		return m, m.waitForWallUnreadUpdate()
	case wallGroupCountUpdateMsg:
		// Тот же трёхвариантный контракт, что у живых сообщений и живых
		// непрочитанных: закрытый канал восстанавливать нечем, нераспознанный
		// апдейт пропускается с переподпиской, годный меняет только число.
		if msg.closed {
			return m, nil
		}
		if !msg.valid {
			return m, m.waitForWallGroupCountUpdate()
		}
		m = m.applyWallGroupCountUpdate(msg.groupID, msg.memberCount)
		return m, m.waitForWallGroupCountUpdate()
	case wallUserStatusUpdateMsg:
		if msg.closed {
			return m, nil
		}
		if !msg.valid {
			return m, m.waitForWallUserStatusUpdate()
		}
		m = m.applyWallUserStatusUpdate(msg.userID, msg.status)
		return m, m.waitForWallUserStatusUpdate()
	case wallUserProfileUpdateMsg:
		// updateUser — снимок пользователя целиком (имя и статус вместе). На
		// стене имя не показывается отдельным полем, поэтому берём из него
		// только статус. Именно этим апдейтом, а не updateUserStatus, приходит
		// снимок статуса: updateUserStatus на загрузке не приходит вовсе
		// (проверено вживью).
		if msg.closed {
			return m, nil
		}
		if !msg.valid {
			return m, m.waitForWallUserProfileUpdate()
		}
		m = m.applyWallUserProfileUpdate(msg.userID, msg.status)
		return m, m.waitForWallUserProfileUpdate()
	case wallFoldersUpdateMsg:
		// Тот же контракт, что и у живых сообщений. Пришёл новый список папок —
		// его состав надо перечитать: у переименованной папки тот же id, а у
		// удалённой id исчезает, и отметки без живой папки фильтру ничего не
		// говорят (см. applyWallFoldersUpdate).
		if msg.closed {
			return m, nil
		}
		if !msg.valid {
			return m, m.waitForWallFoldersUpdate()
		}
		m = m.applyWallFoldersUpdate(msg)
		// Пересборка видимого списка нужна и здесь: папки входят в формулу
		// фильтра, и отметка, снятая удалением папки, должна убрать её ограничение
		// сразу, а не после следующего снимка стены.
		m = m.rebuildVisible(false)
		// Открытое меню пересобирается тоже: в нём могла быть строка удалённой
		// папки, и нажатие на неё включило бы несуществующее ограничение.
		if m.filterMenu != nil {
			m.filterMenu = m.filterMenu.rebuilt(m.filter, m.folders)
		}
		return m, tea.Batch(m.waitForWallFoldersUpdate(), m.wallFolderChatsCmd(m.folders))
	case wallFolderChatsMsg:
		// Состав папок пришёл: карта «чат → папки» и видимый список.
		m = m.applyWallFolderChats(msg)
		return m.rebuildVisible(false), nil
	case wallDeleteUpdateMsg:
		// Тот же трёхвариантный контракт, что у живых сообщений: закрытый
		// канал восстанавливать нечем, нераспознанный апдейт пропускается с
		// переподпиской, годный убирает удалённые сообщения из переписки и, если
		// удалённым было именно сообщение карточки источника, перезапрашивает
		// его новое последнее.
		m, cmd := m.applyWallDeleteUpdate(msg)
		return m, cmd
	case wallCardLatestMsg:
		// Ответ на точечный перезапрос последнего сообщения источника. Карточка
		// при этом меняется (новое сообщение, или снятие карточки опустевшего
		// источника), а значит меняется и источник под курсором — в широком
		// режиме тогда обязана смениться и переписка (syncWallZoomToCursor молчит,
		// если источник тот же, и сеть зря не дёргается).
		m = m.applyWallCardLatest(msg)
		return m.syncWallZoomToCursor()
	case wallSendMessageMsg:
		// Отправленное сообщение может оказаться в другом источнике, чем тот, на
		// котором стоит курсор стены (в широком режиме поле отправляет в открытую
		// переписку), и живой апдейт ответа сдвинет поток — панель обязана
		// переехать вместе с курсором.
		m = m.applyWallSendMessage(msg)
		return m.syncWallZoomToCursor()
	case deleteMessageMsg:
		// Удаление убирает карточку из потока, и курсор стены на её месте может
		// оказаться на другом источнике — тогда меняется и переписка.
		m = m.applyDeleteMessage(msg)
		return m.syncWallZoomToCursor()
	case tea.MouseMsg:
		// Мышь у стены нужна только ради того, чтобы терминал не подменял колесо
		// десятком нажатий ↑/↓: без явного MouseMode (см. View) терминалы, не
		// умеющие отдавать мышь приложению, транслируют вращение колеса именно так
		// — по одному нажатию на «строку прокрутки», а ↑/↓ в стене двигают курсор
		// по карточкам, и одно движение колеса уводило стену через весь поток.
		//
		// События сюда доходят именно затем, что View() объявляет
		// MouseModeCellMotion, и намеренно остаются без обработки: колесо как
		// прокрутка в этой задаче не заводилось и двигать ни курсор, ни окно
		// стены не должно.
		return m, nil
	case spinnerTickMsg:
		m.frame++
		return m, spinnerTickCmd()
	case systemNoticeExpiredMsg:
		// Гасится только та версия сообщения, ради которой таймер и был заведён:
		// за эти пять секунд сообщение могло смениться, и таймер от старого
		// погасил бы новое раньше срока (та же сверка номера попытки, что у
		// applyWallZoomLoaded).
		if m.notice != nil && m.notice.id == msg.id {
			m.notice = nil
		}
		return m, nil
	case cursor.BlinkMsg:
		// Мигание каретки в v2 ведёт сам виджет на своих часах, и без пересылки его
		// сообщений обратно в Update каретка просто стоит на месте.
		if m.input == nil {
			return m, nil
		}
		updated, cmd := m.input.Update(msg)
		m.input = &updated
		return m, cmd
	case tea.KeyPressMsg:
		// Ctrl+C — выход. Без этого в реальном терминале программу нечем закрыть:
		// raw-режим bubbletea отключает обычную обработку SIGINT терминалом, и
		// Ctrl+C доходит до Update как обычное нажатие, которое иначе просто
		// ушло бы в поле ввода символом.
		//
		// Выход остаётся выше модалки подтверждения: это существующий принцип
		// окна, а не часть подтверждения. В остальном порядок веток тот же, что
		// был до появления конфигурации, — меняется только способ сравнения
		// клавиши (см. keymap.go).
		if m.keymap.pressed(keyQuit, msg) {
			return m, tea.Quit
		}
		// Открытая модалка подтверждения перехватывает ввод раньше всех
		// остальных веток: пока человек не ответил на вопрос, ни стрелки, ни
		// ввод текста, ни Ctrl+R не должны срабатывать — иначе то же нажатие
		// удалило бы сообщение и заодно сдвинуло курсор или ушло в поле.
		if m.showConfirm {
			return m.updateConfirm(msg)
		}
		// Открытое меню фильтра перехватывает ввод раньше всех остальных веток —
		// по той же причине, что и модалка подтверждения: переключение галки не
		// должно заодно сдвинуть курсор стены или уйти в поле ввода. Само
		// открытие (эта же клавиша) обрабатывается ВНУТРИ меню (см.
		// updateFilterMenu), поэтому повторное нажатие закрывает его, а не
		// открывает заново.
		if m.filterMenu != nil {
			return m.updateFilterMenu(msg)
		}
		if m.keymap.pressed(keyOpenFilter, msg) {
			// Открытие меню фильтра. Живой предпросмотр означает, что закрытие
			// меню НЕ откатывает сделанное: изменения уже применены к стене и
			// сохранены (см. closeFilterMenuAndSave), и повторное открытие
			// показывает ровно то, что человек выбрал.
			m.openFilterMenu()
			return m, nil
		}
		// Ctrl+R — ответ на сообщение под курсором. Цель фиксируется здесь и
		// больше не едет за курсором: человек выбрал конкретное сообщение, и
		// стрелками по стене ответ поехал бы не туда. Откуда берётся сообщение —
		// из переписки или из карточки стены — решает startReply по тому, в фокусе
		// ли сейчас переписка (см. zoomHasFocus).
		if m.keymap.pressed(keyReply, msg) {
			return m.startReply(), nil
		}
		// Tab переключает фокус по кругу: лента → панель 1 → панель 2 → лента. Панели,
		// в которых ничего не открыто, в круг не попадают — фокусироваться в пустоту
		// незачем, и нажатие ушло бы дальше по кругу (см. nextFocusPanel).
		//
		// Shift+Tab идёт по тому же кругу в обратную сторону: без него вернуться
		// на шаг назад нечем, а круг из двух панелей и ленты без обратного хода
		// — это половина круга.
		//
		// Перехватывается только там, где фокусировать вообще есть что: в широком
		// режиме при открытой переписке. В узком переписка и так единственный экран,
		// отдельного фокуса нет, и нажатие уходит в поле как и раньше.
		if m.focusable() {
			// Направление ищется отдельной переменной, а не через switch с
			// return внутри case: break из switch вышел бы только из самого
			// switch, и нажатие любой ДРУГОЙ клавиши в широком режиме ушло бы
			// обратно вниз по цепочке, мимо стрелок, Enter и Delete.
			direction := 0
			if m.keymap.pressed(keyFocusNext, msg) {
				direction = 1
			} else if m.keymap.pressed(keyFocusPrev, msg) {
				direction = -1
			}
			if direction != 0 {
				m.focusPanel = m.stepFocusPanel(direction)
				// Раскладка подсказок под полем пересчитывается здесь же, как и при
				// любой другой смене состояния, влияющей на поле (см. applyLayout).
				m.applyLayout()
				return m, nil
			}
		}
		// Стрелки и страницы листают ТО, что сейчас в фокусе: переписку, если
		// фокус на ней, иначе стену (на стене подсказка под полем так и обещает
		// «↑ лента»). Остальные нажатия уходят в поле.
		//
		// Ctrl+1 и Ctrl+2 открывают источник под курсором стены в соответствующую
		// панель переписки и ставят фокус на неё (решение человека, 2026-10-01).
		// Проверки идут ДО Select: иначе назначенный на отправку Enter проглотил бы
		// их, а настроенный на ctrl+1 — нет.
		//
		// В обычном широком режиме (панель одна) обе клавиши открывают её же: там
		// выбирать не из чего, и отдельный отказ выглядел бы сломанной клавишей.
		for _, binding := range []struct {
			action keyAction
			panel  wallPanel
		}{
			{keyOpenPanel1, panelChat1},
			{keyOpenPanel2, panelChat2},
		} {
			if !m.keymap.pressed(binding.action, msg) {
				continue
			}
			next, cmd := m.openWallCursorZoomIn(binding.panel)
			// Фокус ставится на панель В НОВОЙ модели: переписка открывается внутри
			// openWallCursorZoomIn, и проверка по исходной m нашла бы там пустую
			// панель всегда — Ctrl+2 не открывал бы ничего.
			if zoom := next.panelZoom(binding.panel); zoom != nil {
				next.focusPanel = binding.panel
			}
			next.applyLayout()
			return next, cmd
		}
		// Проверки идут по одной на действие, а не общим switch по коду клавиши:
		// набор клавиш теперь задаёт конфигурация, и одна и та же клавиша может
		// быть назначена сразу двум действиям (или ни одному) — switch по коду
		// тогда выбрал бы ровно одну ветку и молча проигнорировал бы вторую.
		if m.keymap.pressed(keyMoveUp, msg) {
			return m.moveFocused(-1)
		}
		if m.keymap.pressed(keyMoveDown, msg) {
			return m.moveFocused(1)
		}
		if m.keymap.pressed(keyPageUp, msg) {
			return m.pageFocused(-1)
		}
		if m.keymap.pressed(keyPageDown, msg) {
			return m.pageFocused(1)
		}
		if m.keymap.pressed(keyBack, msg) {
			// Слоёная отмена, порядок ступеней важен — см. cancelWallFocus.
			return m.cancelWallFocus(), nil
		}
		if m.keymap.pressed(keySelect, msg) {
			// Enter — отправка, а не перенос строки (перенос живёт на ctrl+j, как
			// и обещает строка подсказок). Разбор — в submitInput: там и пустое
			// поле, и режим ответа.
			return m.submitInput()
		}
		if m.keymap.pressed(keyDeleteMessage, msg) {
			// Delete — удаление сообщения, с вопросом «Да/Нет». Перехватывается
			// здесь, до m.input.Update, и по той же причине, что и Ctrl+R: на
			// стене нажатие не должно попадать в поле символом. Содержимое поля
			// на это не смотрит — ровно как Ctrl+R: человек печатает ответ, нажал
			// Delete, и хочет удалить сообщение, а не стереть букву в черновике.
			// Какое именно сообщение — переписки или карточки стены — решает
			// openConfirmDeleteMessage по тому же условию, что и Ctrl+R (см.
			// zoomHasFocus). На пустой стене Delete не делает ничего
			// (openConfirmDeleteMessage выходит молча).
			m.openConfirmDeleteMessage()
			return m, nil
		}
		if m.input == nil {
			return m, nil
		}
		rowsBefore := inputVisualRows(*m.input)
		updated, cmd := m.input.Update(msg)
		m.input = &updated
		keepInputVisibleAfterGrowth(m.input, rowsBefore)
		m.applyLayout()
		return m, cmd
	default:
		return m, nil
	}
}

func (m Model) View() tea.View {
	// Модалка подтверждения и меню фильтра накладываются по очереди, а не
	// выбираются: оба оверлея вклеиваются в готовые строки экрана, и второй,
	// наложенный на первый, просто окажется сверху. Одновременно открыты они быть
	// не могут — меню перехватывает весь ввод, а модалка открывается нажатием вне
	// меню, — но проверять это здесь незачем, порядок наложения и так даёт
	// предсказуемую картинку при любом состоянии.
	v := tea.NewView(m.overlayFilter(m.overlayConfirm(m.renderScreen())))
	v.AltScreen = true
	// Мышь захватывается явно, а не оставляется терминалу: иначе колесо
	// превращается в десяток нажатий ↑/↓, а они листают стену (см. раздел
	// tea.MouseMsg в Update). Тот же режим, что у ленты tgcli.
	v.MouseMode = tea.MouseModeCellMotion
	// Фон стены (PaletteBackgroundMain) красится по ячейкам — на каждой ячейке
	// экрана, включая пустые строки и боковые поля. Раньше он намеренно НЕ
	// красился (см. foregroundBackgroundStyle) и отдавался терминалу: общая
	// команда OSC 11 плюс «родной» фон там, где ничего не нарисовано. OSC 11 не
	// применяется видимо ни в Apple Terminal, ни в Warp, и фон из-за этого
	// просто пропадал — без символов в строке его не было видно совсем, а после
	// текста обрывался на боковом поле (человек заметил вживую, 2026-09-30).
	//
	// Первый диагноз («дизеринг цветового управления ColorSync, специфичный для
	// Apple Terminal.app») был неверным: полосы воспроизвелись и в Warp, а
	// байтовый разбор SGR показал, что фон теряется из-за безусловного
	// предположения `ultraviolet` о capability `bce` при стирании через
	// ansi.EL/ECH (см. подробнее в foregroundBackgroundStyle и задачу 0160).
	// Цвет при этом ни при чём — сплошной #000000 полос не убирает.
	//
	// v.BackgroundColor — независимый и оставленный по просьбе человека
	// механизм: команда «фон по умолчанию — вот такой» отправляется ОДИН раз за
	// сеанс (bubbletea's cursedRenderer шлёт OSC 11 при первом рендере и при
	// смене значения) и покрывает область терминала, которую приложение не
	// рисует вовсе, — историю прокрутки, поля за пределами кадра.
	v.BackgroundColor = PaletteBackgroundMain
	return v
}

// wallNotice — что показать на месте пустой стены.
//
// Тексты взяты из того, что известно наверняка, и не выдуманы: «Загрузка…» при
// загрузке, причина сбоя при ошибке, «Чатов нет» когда данных правда не
// пришло. Список чатов с 404 на каждый чат (бывает на не полностью досинхронизированном
// аккаунте) — тоже «Чатов нет»: список чатов пуст, а изобретать для этого
// отдельную формулировку значило бы рисовать на экране то, чего не знаешь.
//
// Пока стена загружается, спиннер в нижней строке уже говорит «идёт» — повторять
// это же слово наверху незачем, поэтому при загрузке строка пустая.
func (m Model) wallNotice() string {
	switch {
	case m.loading:
		return ""
	case m.loadError != "":
		return m.loadError
	default:
		return "Чатов нет"
	}
}

// rebuildVisible — пересобрать видимый список стены из полного потока по текущему
// фильтру и удержать курсор.
//
// Вызывается после ЛЮБОЙ правки потока (снимок, живой апдейт, удаление,
// смена числа непрочитанных) и после ЛЮБОЙ смены фильтра — то есть это
// единственное место, где m.cards вообще появляется из m.source. Отдельной
// проверки «а не изменилось ли что-нибудь» здесь нет намеренно: она стоила бы
// обхода карточек впустую в самом частом случае, когда поток не тронут.
//
// Курсор держится на ТОМ ЖЕ источнике, а не на том же номере: пересборка
// меняет длину списка, и номер после неё указывал бы на чужую карточку (ровно
// тот же довод, по которому applyWallMessageUpdate запоминает адрес источника, а
// не индекс). Источник, скрытый новым фильтром, курсора не уводит никуда
// осмысленно — остаётся прежний номер, то есть ближайшая видимая карточка.
//
// followLatest — «человек смотрит на самое свежее»: курсор встаёт на последнюю
// видимую карточку, а окно прижимается к низу scrollTopToBottom, а не
// clampScrollToCursor. Так ведёт себя первая загрузка стены и живое сообщение,
// пришедшее вниз потока (см. wallLoadedMsg и applyWallMessageUpdate).
func (m Model) rebuildVisible(followLatest bool) Model {
	// Адрес источника под курсором запоминается ДО пересборки: после неё
	// m.cards — уже другой список, и прежний индекс указывал бы не туда.
	var anchorChatID int64
	if len(m.cards) > 0 {
		anchorChatID = m.cards[clampWallCursor(m.cursor, len(m.cards))].ChatID
	}

	m.cards = m.filterCards()

	if followLatest {
		m.cursor = clampWallCursor(len(m.cards)-1, len(m.cards))
		m.scrollTop = scrollTopToBottom(wallCardHeight, m.cards, m.cursor, m.wallColumnWidth(), m.wallContentHeight())
		return m
	}
	if anchorChatID != 0 {
		if index := indexOfChatCard(m.cards, anchorChatID); index >= 0 {
			m.cursor = index
		}
	}
	m.cursor = clampWallCursor(m.cursor, len(m.cards))
	m.scrollTop = clampScrollToCursor(wallCardHeight, m.cards, m.scrollTop, m.cursor, m.wallColumnWidth(), m.wallContentHeight())
	return m
}

// moveCursor — выбор соседней карточки с зажимом по краям. Выбрана всегда
// ровно одна карточка — та, на которой стоит курсор.
//
// Окно стены едет за курсором: шаг вверх открывает верхние карточки, шаг вниз
// показывает ту, на которую перешли, — старые уходят вверх за экран. Без этого
// курсор доходил бы до невидимых карточек, и на экране не оставалось бы ни одной
// выбранной.
//
// Ширина и высота — те, по которым стена реально нарисована (wallColumnWidth и
// wallContentHeight): в широком режиме это колонка за вычетом контура панели, а
// не терминал, и мерить по терминалу значило бы считать окно по одним размерам,
// а рисовать по другим.
func (m Model) moveCursor(delta int) Model {
	m.cursor = clampWallCursor(m.cursor+delta, len(m.cards))
	m.scrollTop = clampScrollToCursor(wallCardHeight, m.cards, m.scrollTop, m.cursor, m.wallColumnWidth(), m.wallContentHeight())
	return m
}

// moveFocused — стрелка вверх/вниз по тому, что сейчас в фокусе: по сообщениям
// открытой переписки или по карточкам стены.
//
// Обёртка, а не новая навигация: и там, и там курсор и окно двигают уже
// существующие moveCursor и moveWallZoomCursor, и различаются обёртки только
// поводом вызвать их. В широком режиме шаг по стене дополнительно открывает
// переписку нового источника (syncWallZoomToCursor), поэтому возвращает и
// команду.
// focusable — есть ли вообще что переключать фокусом: широкий режим, в котором
// открыта хоть одна панель переписки. В узком переписка занимает весь ввод и
// отдельного фокуса нет.
//
// «Хоть одна», а не «первая» (m.zoom): при двух панелях переписка может
// открыться только во второй, и проверка по первой объявила бы, что фокуситься
// некуда, — Tab перестал бы работать.
func (m Model) focusable() bool {
	if !m.wallPanelMode() {
		return false
	}
	for _, panel := range m.wallChatPanelsOrder() {
		if m.panelZoom(panel) != nil {
			return true
		}
	}
	return false
}

// nextFocusPanel — куда уходит фокус по Tab: лента → панель 1 → панель 2 → лента.
func (m Model) nextFocusPanel() wallPanel {
	return m.stepFocusPanel(1)
}

// prevFocusPanel — куда уходит фокус по Shift+Tab: тот же круг, но назад.
//
// Отдельным вызовом, а не флагом у nextFocusPanel, потому что направление здесь
// не параметр, а отдельное ДЕЙСТВИЕ со своей клавишей в конфигурации: смешивать
// их в одной функции значило бы забыть про одну из половин круга при правке
// другой.
func (m Model) prevFocusPanel() wallPanel {
	return m.stepFocusPanel(-1)
}

// stepFocusPanel — круг фокуса в заданную сторону.
//
// Панели, в которых ничего не открыто, перепрыгиваются, а не останавливают
// круг: иначе после Ctrl+1 фокус ушёл бы в пустую панель 2 и дальше по Tab
// пришлось бы дважды нажимать, чтобы вернуться к ленте.
//
// При фокусе на ПАНЕЛИ круг дальше идёт по панелям и замыкается на ленте, а не
// по кругу панелей: возвращение на ленту нужно человеку чаще всего, и делать его
// одним нажатием — то, ради чего он жал Tab. Лента в обратную сторону уводит на
// последнюю панель с перепиской, а не на первую: иначе Shift+Tab с ленты
// наружу выкидывал бы человека из стены в панель, к которой он не вёл.
func (m Model) stepFocusPanel(direction int) wallPanel {
	order := m.wallChatPanelsOrder()
	for index, panel := range order {
		if m.panelZoom(panel) == nil {
			continue
		}
		if m.focusPanel == panel {
			// С фокусной панели — на соседнюю по кругу в нужную сторону, а
			// край круга замыкается на ленту.
			for next := index + direction; next >= 0 && next < len(order); next += direction {
				if m.panelZoom(order[next]) != nil {
					return order[next]
				}
			}
			return panelWall
		}
	}
	// Фокус на ленте (или на панели, которой уже нет) — на первую панель с
	// перепиской вперёд и на последнюю назад.
	if direction < 0 {
		for index := len(order) - 1; index >= 0; index-- {
			if m.panelZoom(order[index]) != nil {
				return order[index]
			}
		}
		return panelWall
	}
	for _, panel := range order {
		if m.panelZoom(panel) != nil {
			return panel
		}
	}
	return panelWall
}

// moveFocused — стрелка вверх/вниз по тому, что сейчас в фокусе: по сообщениям
// открытой переписки или по карточкам стены.
//
// Обёртка, а не новая навигация: и там, и там курсор и окно двигают уже
// существующие moveCursor и moveWallZoomCursor, и различаются обёртки только
// поводом вызвать их. В широком режиме шаг по стене дополнительно открывает
// переписку нового источника (syncWallZoomToCursor), поэтому возвращает и
// команду.
func (m Model) moveFocused(delta int) (Model, tea.Cmd) {
	if m.zoomHasFocus() {
		m.moveWallZoomCursor(delta)
		return m, nil
	}
	m = m.moveCursor(delta)
	return m.syncWallZoomToCursor()
}

// pageFocused — страница вверх/вниз по тому, что сейчас в фокусе. Обёртка над
// pageScroll и pageWallZoom по той же причине, что и moveFocused.
func (m Model) pageFocused(delta int) (Model, tea.Cmd) {
	if m.zoomHasFocus() {
		m.pageWallZoom(delta)
		return m, nil
	}
	m = m.pageScroll(delta)
	return m.syncWallZoomToCursor()
}

// cancelWallFocus — Esc. Слоёная отмена, и порядок ступеней важен: сначала
// снимается то, что человек выбрал САМ (цель ответа), и только потом — то, в чём
// он находится. Наоборот получилось бы так, что Esc, которым человек снимал
// ответ, заодно выкинул бы его из открытой переписки.
//
// Ступени:
//
//  1. активная цель ответа — гасится только она;
//  2. узкий терминал с открытой перепиской — переписка закрывается, возврат на
//     стену (курсор и окно стены при этом не трогаются);
//  3. широкий терминал с фокусом на переписке — фокус возвращается на список,
//     сама переписка остаётся: в широком режиме ей закрываться некуда, она
//     всегда показывает источник под курсором;
//  4. широкий режим, фокус на ленте, вторая панель открыта — панель закрывается;
//  5. вне переписки — ничего, как и раньше.
func (m Model) cancelWallFocus() Model {
	if m.replyTarget != nil {
		m.replyTarget = nil
		// applyLayout пересчитывает высоту поля по освободившейся строке ответа —
		// иначе стена осталась бы на старой высоте до следующего нажатия.
		m.applyLayout()
		return m
	}
	if m.zoom != nil && !m.wallPanelMode() {
		return m.closeWallZoom()
	}
	// Широкий режим: с панели переписки Esc возвращает на ленту, сама панель
	// остаётся открытой (решение человека, 2026-10-01). Закрыть вторую панель
	// можно только повторным Esc с ленты: одна ступень — одно нажатие, и
	// «сначала выйти, потом закрыть» читается однозначно.
	if m.focusPanel.isChatPanel() {
		m.focusPanel = panelWall
		m.applyLayout()
		return m
	}
	if m.twoPanelPinned() {
		m.zoomPinned = nil
		m.applyLayout()
	}
	return m
}

// pageScroll — прокрутка на страницу вниз (delta > 0) или вверх (delta < 0).
//
// Курсор едет вместе с окном: он стоял в нижней части старого окна, и после
// прокрутки на страницу остался бы за пределами экрана. Подтягивать его обратно к
// прежнему месту бессмысленно — тогда окно вернулось бы назад и прокрутка ничего
// бы не дала, — поэтому сдвиг окна повторяется на курсоре. clampScrollToCursor
// остаётся последней строкой страховки: он держит «курсор виден» на любом
// размере окна, а не только на типовом.
func (m Model) pageScroll(delta int) Model {
	target := scrollPageTop(wallCardHeight, m.cards, m.scrollTop, m.cursor, m.wallColumnWidth(), m.wallContentHeight(), delta)
	if target == m.scrollTop {
		// Окно уперлось в край потока, но курсор ещё может идти дальше в ту же
		// сторону. Оставлять его на месте нельзя: PgUp у самой старой карточки
		// перестал бы что-либо делать, и до начала потока пришлось бы добираться
		// стрелками по одной. Доехал до края — встал на край, как в less и vim.
		edge := 0
		if delta > 0 {
			edge = len(m.cards) - 1
		}
		if m.cursor == edge {
			return m
		}
		m.cursor = edge
		m.scrollTop = clampScrollToCursor(wallCardHeight, m.cards, m.scrollTop, m.cursor, m.wallColumnWidth(), m.wallContentHeight())
		return m
	}
	m.cursor = clampWallCursor(m.cursor+target-m.scrollTop, len(m.cards))
	m.scrollTop = clampScrollToCursor(wallCardHeight, m.cards, target, m.cursor, m.wallColumnWidth(), m.wallContentHeight())
	return m
}

// clampScrollToCursor — окно прокрутки, в котором выбранная карточка видна, а
// экран заполнен настолько, насколько есть чем. Один и тот же зажим для всех
// мест, где окно должно догонять курсор: первая загрузка, навигация стрелками,
// пересчёт под размер терминала. Меряет карточки переданной measure — у стены
// это wallCardHeight, у переписки zoomCardHeight (см. cardHeight).
//
// Три случая для видимости курсора, и правило у каждого своё: курсор выше окна
// — окно подъезжает к нему (прокрутка вверх, открываются верхние карточки);
// курсор ниже окна — окно спускается ровно настолько, чтобы курсор попал в
// кадр, без прыжка на целый экран; курсор в окне — окно не трогаем, иначе список
// полз бы при каждом шаге. После этого — отдельный шаг backfillScrollTop:
// если снизу остался пустой хвост экрана, а сверху есть ещё история, окно
// подтягивает её, пока не заполнит экран целиком (см. backfillScrollTop).
func clampScrollToCursor(measure cardHeight, cards []card, scrollTop, cursor, width, height int) int {
	if len(cards) == 0 || width <= 0 || height <= 0 {
		return clampWallScrollTop(scrollTop, len(cards))
	}
	cursor = clampWallCursor(cursor, len(cards))
	scrollTop = clampWallScrollTop(scrollTop, len(cards))

	switch {
	case cursor < scrollTop:
		scrollTop = cursor
	default:
		if top := scrollTopForCursor(measure, cards, cursor, width, height); top >= scrollTop {
			scrollTop = top
		}
		// Иначе курсор и так виден: чем ниже окно, тем позже в нём курсор, и
		// трогать scrollTop незачем — кроме добивки ниже.
	}
	return backfillScrollTop(measure, cards, scrollTop, cursor, width, height)
}

// wallHeight — высота стены на экране: терминал минус строки под стеной, строки
// над ней (строка фильтра и строка сообщений) и блок ввода. Всё, что считает
// окно прокрутки, берёт высоту отсюда, а не пересчитывает её у себя: две разные
// формулы разошлись бы, и прокрутка поехала бы мимо.
// Строка ответа вычитается через общий replyRows — ею же считается и предел
// роста поля в applyLayout.
func (m Model) wallHeight() int {
	return max(0, m.height-wallReservedRows-wallTopBarRows-wallNoticeRows-m.inputRows-m.replyRows())
}

// applyLayout — пересчёт размеров под текущий терминал и под текущее значение
// поля. Высота поля считается по строкам экрана, а не по строкам значения:
// длинная строка переносится по ширине, и без этого её хвост не помещался бы в
// поле (см. inputVisualRows).
func (m *Model) applyLayout() {
	if m.input == nil {
		m.inputRows = 0
		return
	}
	fieldWidth := max(0, m.width-2*cardMarginH-cardBorderWidth)
	m.input.SetWidth(max(0, fieldWidth-2*inputPaddingH))

	desired := max(inputMinHeight, inputVisualRows(*m.input))
	// Поле не съедает всю стену: минимум строки под стену остаётся всегда, а уж
	// остальное распределяется между полем и стеной. Строка ответа вычитается тем
	// же replyRows, что и в wallHeight, и новые строки каркаса (строка фильтра
	// вверху, строка сообщений) — теми же константами: иначе при выбранном ответе
	// или на длинном значении поля на маленьком терминале поле налезло бы на них,
	// и экран стал бы выше терминала — нижняя строка со спиннером уехала бы за
	// обрезку renderScreen.
	ceiling := max(0, m.height-wallReservedRows-wallTopBarRows-wallNoticeRows-m.replyRows()-inputMinHeight)
	m.inputRows = min(desired, max(inputMinHeight, ceiling))
	m.input.SetHeight(m.inputRows)
}

func (m Model) renderScreen() string {
	if m.width <= 0 || m.height <= 0 {
		return ""
	}
	wallHeight := m.wallHeight()

	lines := make([]string, 0, m.height)
	// Строка фильтра и название открытой переписки — в самом верху, на всю
	// ширину терминала. Раньше здесь стояли два пустых бара, но место под меню
	// так и не понадобилось, а строка с подписью фильтра нужна уже сейчас.
	lines = append(lines, m.renderTopBar(m.width))
	lines = append(lines, m.renderWallZone(m.width, wallHeight)...)
	// Строка системных сообщений — часть потока стены, поэтому стоит сразу под
	// ней и стеной не считается: её место занято всегда, сообщение или нет.
	lines = append(lines, renderSystemNotice(m.notice, m.width))
	lines = append(lines, renderSeparator(m.width))
	if m.input != nil {
		fieldWidth := max(0, m.width-2*cardMarginH-cardBorderWidth)
		// Пустая строка — ответа нет: лишней строки над полем в этом случае не
		// рисуется (её же учитывает replyRows в высоте стены).
		replyContext := ""
		if m.replyTarget != nil {
			replyContext = m.replyTarget.Label
		}
		// Цвет левой границы поля — по ТЕКУЩЕЙ цели ввода, а не зашитый: в строке
		// подсказок человек не видит, куда уйдёт текст (в широком режиме это не
		// обязательно источник под курсором), а граница обязана показывать
		// (см. inputTargetAccent).
		lines = append(lines, renderInputZone(*m.input, fieldWidth, m.inputRows, replyContext, m.hintPairs(), m.inputTargetAccent())...)
	}
	lines = append(lines, renderSeparator(m.width))
	lines = append(lines, renderStatusBar(m.width, m.frame, m.isLoading(), m.username, m.appName, m.version))

	// Экран ровно из m.height строк: лишнее снизу срезается, недостающее добивается
	// фоном. Добор идёт ПЕРЕД нижней строкой — она обязана остаться последней,
	// иначе спиннер с названием уехал бы в середину экрана.
	if len(lines) >= m.height {
		return strings.Join(lines[:m.height], "\n")
	}
	status := lines[len(lines)-1]
	body := lines[:len(lines)-1]
	for len(body) < m.height-1 {
		body = append(body, renderedFill(m.width, PaletteBackgroundMain))
	}
	return strings.Join(append(body, status), "\n")
}

// renderWall — карточки стены сверху вниз, начиная с scrollTop, между соседними по
// одной пустой строке (в макете это зазор карточек, а не линия-разделитель).
// Каждая карточка — ровно две строки (см. renderCard), выбранная отличается
// только фоном.
//
// Если стена не влезает в отведённую высоту, она обрезается снизу. Обрезается
// хвост последней не поместившейся карточки, а не вся стена после неё: на узком
// терминале колонка текста сужается до нескольких ячеек, длинный текст в ней
// переносится на десятки строк, и обрыв «после первой не влезшей карточки» прятал
// бы всю стену целиком.
func renderWall(cards []card, scrollTop, cursor, width, height int, notice string) []string {
	return renderWallWith(cards, scrollTop, cursor, width, height, notice, renderCard)
}

// renderWallWith — стена, карточки которой рисует переданный render. Отдельная
// функция не для красоты: у стены есть два вызова с РАЗНЫМИ правилами карточки
// (широкий режим скрывает у карточки под курсором время и превью, см.
// renderWallCardBlock), и без параметра второй вызов тихо уехал бы на обычный
// renderCard — то есть на экран попала бы ровно та карточка, которую задача
// запретила показывать.
func renderWallWith(cards []card, scrollTop, cursor, width, height int, notice string, render func(card, int, bool) []string) []string {
	if width <= 0 || height <= 0 {
		return nil
	}
	// Заглушка стоит на месте стены, пока карточек нет: и при загрузке (идёт, скоро
	// будут), и при сбое (не придут), и когда у аккаунта правда нет чатов. Строка
	// одна и приглушённая — она должна сообщать, а не занимать экран.
	if len(cards) == 0 && notice != "" {
		return []string{fitLine(
			renderedFill(cardMarginH, PaletteBackgroundMain)+
				foregroundBackgroundStyle(PaletteTextFaint, PaletteBackgroundMain).Render(truncateVisible(notice, max(0, width-2*cardMarginH)))+
				renderedFill(cardMarginH, PaletteBackgroundMain),
			width, PaletteBackgroundMain)}
	}
	return renderCardList(cards, scrollTop, cursor, width, height, render)
}

// renderCardList — строки списка карточек начиная с top: между соседними по
// одной пустой строке, обрезка хвоста, добор фоном до высоты зоны.
//
// Общая отрисовка для стены и для переписки открытого чата (задача 0155): сами
// списки разные (карточки источников и сообщения одного чата), а правила сборки
// строк — те же самые, и разойтись они могут только в одном месте, а не в двух
// копиях. Что именно рисует блок элемента, задаёт render.
func renderCardList(cards []card, top, cursor, width, height int, render func(card, int, bool) []string) []string {
	if width <= 0 || height <= 0 {
		return nil
	}
	lines := make([]string, 0, height)
	// Индексы карточек в этом цикле — индексы во всём списке, а не в окне: иначе
	// выбранной оказалась бы не та карточка, на которой стоит курсор.
	for index := clampWallScrollTop(top, len(cards)); index < len(cards); index++ {
		if len(lines) > 0 {
			// Зазор между карточками — одна пустая строка основного фона.
			if len(lines)+wallGap >= height {
				break
			}
			lines = append(lines, renderedFill(width, PaletteBackgroundMain))
		}
		block := render(cards[index], width, index == cursor)
		remaining := height - len(lines)
		if len(block) > remaining {
			block = block[:remaining]
		}
		lines = append(lines, block...)
		if len(lines) >= height {
			break
		}
	}
	for len(lines) < height {
		lines = append(lines, renderedFill(width, PaletteBackgroundMain))
	}
	return lines
}

// renderSeparator — разделитель зон во всю ширину экрана за вычетом боковых
// полей.
func renderSeparator(width int) string {
	background := PaletteBackgroundMain
	margin := renderedFill(cardMarginH, background)
	line := foregroundBackgroundStyle(PaletteBorder, background).
		Render(strings.Repeat("─", max(0, width-2*cardMarginH)))
	return margin + line + margin
}

// Служебное оформление строк. Все пробелы красятся фоном явно: некрашенный пробел
// ушёл бы в собственный фон терминала и рвал строку (см. задачу 0146).

// foregroundBackgroundStyle красит фон явно для ЛЮБОГО значения, включая
// PaletteBackgroundMain: фон должен быть на каждой ячейке экрана, а не только
// там, где есть содержимое. Раньше здесь стояло исключение
// `background != PaletteBackgroundMain` (вместе с таким же в renderedFill) —
// фон стены тогда отдавался родному фону терминала и на OSC 11, который не
// применяется видимо ни в Apple Terminal, ни в Warp, из-за чего фон на экране
// просто пропадал: без символов в строке его не было видно совсем, а после
// текста обрывался на боковом поле (человек заметил вживую, 2026-09-30).
//
// ВАЖНО, и это не то же самое, что «фон стены»: настоящая причина полос при
// сплошной заливке — НЕ цвет и не терминал. `ultraviolet` вместо буквальной
// записи пробелов с фоном иногда шлёт стирание (ansi.EL/ECH) и безусловно
// рассчитывает, что терминал зальёт стёртое текущим фоном — это предположение
// про capability `bce`, в самой библиотеке помеченное комментарием «NOTE: This
// assumes that the terminal supports bce» (terminal_renderer.go, canClearWith)
// и НЕ проверяемое по флагам. Поэтому поячеечная заливка — необходимое
// условие для фона на каждой ячейке, но само по себе она полос не гарантирует
// и не устраняет: это проверяется отдельно, задача 0160.
func foregroundBackgroundStyle(foreground, background color.Color) lipgloss.Style {
	return lipgloss.NewStyle().Foreground(foreground).Background(background)
}

func renderedFill(width int, background color.Color) string {
	if width <= 0 {
		return ""
	}
	return lipgloss.NewStyle().Background(background).Render(strings.Repeat(" ", width))
}

// fitLine — строка, обрезанная до ширины и дополненная до неё фоном.
func fitLine(line string, width int, background color.Color) string {
	if width <= 0 {
		return ""
	}
	if cellWidth(line) > width {
		line = lipgloss.NewStyle().MaxWidth(width).Render(line)
	}
	if visible := cellWidth(line); visible < width {
		line += renderedFill(width-visible, background)
	}
	return line
}

func splitLines(content string) []string {
	if content == "" {
		return []string{""}
	}
	return strings.Split(strings.TrimSuffix(content, "\n"), "\n")
}

// truncateVisible — обрезка строки многоточием до ширины. Многоточие не съедает
// всю строку: если на него самого места не остаётся, обрезок бесполезен.
func truncateVisible(text string, width int) string {
	if width <= 0 {
		return ""
	}
	if cellWidth(text) <= width {
		return text
	}
	if width == 1 {
		return ellipsis
	}

	var builder strings.Builder
	used := 0
	for _, r := range text {
		runeWidth := cellWidth(string(r))
		if used+runeWidth+1 > width {
			break
		}
		builder.WriteRune(r)
		used += runeWidth
	}
	if builder.Len() == 0 {
		return ellipsis
	}
	return builder.String() + ellipsis
}
