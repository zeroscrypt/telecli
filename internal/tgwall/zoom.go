// Экран одного источника — открытая переписка. Механика целиком перенесена из
// зума чата ленты tgcli (internal/tgclitui/zoom.go): загрузка истории с защитой
// от гонки при быстром открытии/закрытии (loadID), живая вставка новых
// сообщений в открытую переписку, открытие/закрытие. Написано заново под модель
// стены, но не по памяти: у стены своя нумерация карточек, своё окно прокрутки и
// свой адресат отправки.
//
// Два способа показать ОДНО И ТО ЖЕ состояние, различаются они только шириной
// терминала (wallPanelMode), а не настройкой:
//
//   - узкий терминал (m.width <= wallZoomThreshold) — переписка занимает всю
//     ширину вместо стены и открывается ЯВНО, по Enter с пустым полем;
//   - широкий терминал (m.width > wallZoomThreshold) — стена сужается до
//     колонки wallPanelColumnWidth, а переписка рисуется справа и открыта ВСЕГДА,
//     сама следуя за курсором стены (как превью в почтовых клиентах).
//
// Ни загрузка, ни вставка живых сообщений, ни отправка, ни ответ, ни отрисовка
// списка не знают, какой из двух режимов на экране: это один компонент, и второго
// пути под второй повод здесь нет (см. «Единый компонент» в задаче 0155).

const (
	// wallZoomMessagesLimit — сколько последних сообщений запрашивается при
	// открытии переписки. Ровно то же число, что у зума чата ленты tgcli
	// (chatZoomMessagesLimit в internal/tgclitui/zoom.go): это не угадывание, а
	// уже согласованная константа проекта.
	wallZoomMessagesLimit = 50

	// wallZoomThreshold — граница ширины терминала между узким и широким
	// режимами. Число зафиксировано человеком явно (2026-09-30) и НЕ выводится
	// из прочей геометрии экрана. Совпадает по значению с cardTitleTimeMaxWidth
	// (потолок колонки «имя + время»), но это две независимые величины: одна про
	// вёрстку карточки, другая про раскладку экрана, и связаны они только
	// решением человека выбрать одно и то же число.
	wallZoomThreshold = 65

	// wallTwoPanelThreshold — граница между обычным широким режимом и
	// трёхколоночным, где справа от ленты стоят ДВЕ панели переписки. Задана
	// человеком явно (2026-10-01: «если ширина окна больше 110») и не выводится
	// из wallZoomThreshold: два порога означают две разные раскладки экрана, и
	// выводить один из другого значило бы менять ширину ленты вместе с числом
	// панелей, а лента задана отдельно и не меняется (см. wallPanelColumnWidth).
	wallTwoPanelThreshold = 110

	// wallPanelColumnWidth — ширина колонки стены, когда справа открыта
	// переписка. Задана человеком явно (2026-09-30) и не вычисляется из
	// wallZoomThreshold.
	wallPanelColumnWidth = 30

	// wallPanelGapWidth — зазор между колонкой стены и панелью переписки: одна
	// ячейка, как и зазор между соседними карточками стены (wallGap).
	wallPanelGapWidth = 1

	// wallPanelOutlineInset — сколько ячеек контур панели забирает у её
	// содержимого ПО ШИРИНЕ и ПО ВЫСОТЕ: по одной с каждой из двух сторон
	// (слева/справа и сверху/снизу).
	//
	// Место под контур зарезервировано ВСЕГДА, а не только когда панель в фокусе:
	// иначе переключение фокуса по Tab двигало бы содержимое на две ячейки и на
	// две строки, и раскладка прыгала бы в момент нажатия (тот же приём, что у
	// левой границы карточки, см. renderWallCard).
	wallPanelOutlineInset = 2

	// wallZoomHeaderRows — строк занимает шапка переписки (название источника).
	// Занимает она свой slot ВНУТРИ зоны стены, и то только в компактном режиме:
	// в широком режиме название чата стоит в верхней строке экрана, над панелью
	// (см. renderTopBar), и вторая копия того же названия в шапке панели была бы
	// дублем, а панель — на строку короче.
	wallZoomHeaderRows = 1

	// zoomBubbleMaxWidthPercent — какую долю доступной ширины может занять блок
	// одного сообщения. Не во всю ширину панели: сообщения, размазанные по
	// краям, читаются хуже, а колонка переписки на широком терминале шире любой
	// разумной строки текста. Значение механическое, подобрано по месту.
	zoomBubbleMaxWidthPercent = 70
)

// panelContentHeightFor — высота содержимого панели широкого режима при высоте
// зоны zoneHeight: зона минус контур с обеих сторон (см. wallPanelOutlineInset).
//
// Общая для двух вызывающих (Model.wallContentHeight и renderWallZone), а не
// повторённая арифметика в каждом: та же формула, написанная дважды, разошлась
// бы от одной правки в одном месте и не в другом, и ни один экранный тест этого
// не поймал бы (см. TestPanelContentHeightForSubtractsOutlineInset — проверка по
// значению именно потому, что panelOutline защитно обрезает лишнее содержимое по
// хвосту, и экранная проверка этот класс ошибки не видит: результат совпадает
// с правильным, даже если сюда передать необрезанную зону целиком).
func panelContentHeightFor(zoneHeight int) int {
	return max(0, zoneHeight-wallPanelOutlineInset)
}

// wallZoom — открытая переписка одного источника.
//
// Состояние дополнительного режима, а не набор полей в Model (тот же стиль, что
// у replyTarget в send.go): переписка либо открыта целиком, либо не открыта
// вовсе, и m.zoom == nil означает ровно «переписки на экране нет» — ни панели
// справа, ни полноэкранного окна.
type wallZoom struct {
	// chatID — источник переписки. Он же часть сверки ответа загрузки (п.2
	// задачи 0155): без него быстрое переключение между источниками применило бы
	// уже устаревшую переписку.
	chatID int64
	// title — название источника для шапки экрана или панели. Заголовок
	// карточки стены, а не пустая строка: в открытой переписке показывать имя
	// источника в каждом сообщении незачем, а шапка обязана его назвать.
	title string
	// messages — переписка, старейшее сверху (так её отдаёт auth.GetMessages).
	messages []auth.Message
	// cursor — выбранное сообщение: цель ответа (Ctrl+R) и то, чем двигают
	// стрелки, когда фокус на переписке.
	cursor int
	// scrollTop — индекс первого видимого сообщения. Окно своё, у списка
	// сообщений оно не то же, что у стены, хотя считается тем же механизмом.
	scrollTop int
	// loading — идёт ли загрузка истории. Пока она не кончилась, на месте списка
	// «Загрузка истории…», а не пустота (человек смотрит на пустую переписку и
	// не может отличить «ещё грузится» от «сообщений нет»).
	loading bool
	// loadID — номер попытки загрузки, под которым открыта ЭТА переписка.
	// Сверяется с номером в ответе: пока человек перебирает источники курсором,
	// в полёте может быть несколько запросов истории, и примениться должен
	// только последний (см. applyWallZoomLoaded).
	loadID uint64
	// panel — номер панели, в которой открыта эта переписка. Часть сверки
	// ответа загрузки наравне с chatID и loadID: при двух панелях одинаковый
	// источник, открытый дважды, даёт совпадающую пару (chatID, loadID), и без
	// номера панели ответ второй применился бы к первой.
	panel wallPanel
}

// wallZoomLoadedMsg — ответ на запрос истории переписки.
type wallZoomLoadedMsg struct {
	// panel — панель, для которой запрашивалась история. Обязателен рядом с
	// chatID и loadID: без него при двух панелях ответ применился бы к первой
	// (см. wallZoom.panel).
	panel    wallPanel
	chatID   int64
	loadID   uint64
	messages []auth.Message
	err      error
}

// wallPanelMode — широкий ли терминал: при m.width > wallZoomThreshold зона
// стены делится на колонку карточек и панель переписки. Отдельно от «открыта ли
// переписка» (m.zoom): на широком терминале переписка открыта всегда, и сама
// раскладка экрана от её содержимого не зависит.
func (m Model) wallPanelMode() bool {
	return m.width > wallZoomThreshold
}

// wallColumnWidth — ширина, по которой рисуется и меряется колонка карточек
// стены. В узком режиме это вся ширина терминала, в широком — колонка
// рядом с панелью за вычетом контура панели.
//
// Единое место намеренно: окно прокрутки стены считается по этой ширине в
// восьми местах (движение курсора, страница, ресайз, живой апдейт, удаление), и
// две разные формулы разошлись бы ровно там, где зазор между колонками уже
// есть.
//
// В широком режиме это ширина СОДЕРЖИМОГО колонки, а не вся колонка: по краям
// панели стоит контур, и он занимает свои ячейки у обеих колонок зоны (см.
// wallPanelOutlineInset и renderWallZone). Считать по всей колонке значило бы
// мерять окно по одной ширине, а рисовать по другой.
func (m Model) wallColumnWidth() int {
	if m.wallPanelMode() {
		return max(0, wallPanelColumnWidth-wallPanelOutlineInset)
	}
	return m.width
}

// wallContentHeight — высота, по которой рисуется и меряется содержимое панелей
// широкого режима. Тот же приём и по той же причине, что у wallColumnWidth по
// ширине: высота зоны (m.wallHeight) — это каркас экрана, а строки у краёв панелей
// занимает контур, и без этого вычитания окно прокрутки считалось бы на две
// строки выше, чем на самом деле нарисовано (внизу колонки оставалась бы пустая
// полоса, а нижний край карточки под курсором мог бы уйти за нижний контур).
//
// Запас остаётся и в том редком состоянии, когда контур не рисуется вовсе (нет
// открытой переписки, см. wallPanelOutlined): посчитанное на две строки меньше
// окно в том случае лишь оставит у низа колонки пустую полосу, зато правило
// «одна формула на все места» не разойдётся с отрисовкой ни в одном из них.
func (m Model) wallContentHeight() int {
	if m.wallPanelMode() {
		return panelContentHeightFor(m.wallHeight())
	}
	return m.wallHeight()
}

// zoomHasFocus — открыта ли переписка И в фокусе. Это условие решает всё, что
// зависит от того, куда смотрит человек: что двигают стрелки, откуда берётся
// цель ответа (Ctrl+R) и кому уходит текст по Enter.
//
// В узком режиме фокус на переписке всегда, когда она открыта: она занимает
// весь ввод, отдельного «фокуса» там не существует, поэтому и Tab в узком
// режиме не перехватывается. В широком режиме это отдельное состояние
// (m.zoomFocused), переключаемое Tab, и по умолчанию фокус на списке.
func (m Model) zoomHasFocus() bool {
	if m.wallPanelMode() {
		// Фокус на панели переписки. Панель берётся по номеру фокуса, но если в
		// ней ничего нет, фокус САМ СЕБЕ возвращается на ленту: иначе «фокус в
		// переписке» указывал бы в пустоту, отправка шла бы в никуда, а Enter на
		// панели без переписки обещал бы отправку. Это не молчаливая подмена, а
		// ровно то, что видит человек: пустой панели с фокусом на экране нет.
		if m.focusPanel.isChatPanel() && m.panelZoom(m.focusPanel) != nil {
			return true
		}
		return false
	}
	// Узкий режим: переписка занимает весь ввод, отдельного фокуса нет.
	return m.zoom != nil
}

// wallZoomLoadedCmd — запрос истории переписки источника. Тот же auth.GetMessages
// и тот же предел, что у зума чата ленты tgcli.
func (m Model) wallZoomLoadedCmd(panel wallPanel, chatID int64, loadID uint64) tea.Cmd {
	ctx := m.ctx
	if ctx == nil {
		ctx = context.Background()
	}
	client := m.client
	return func() tea.Msg {
		if client == nil {
			return wallZoomLoadedMsg{panel: panel, chatID: chatID, loadID: loadID, err: errNoTDLibClient}
		}
		messages, err := auth.GetMessages(ctx, client, chatID, wallZoomMessagesLimit)
		return wallZoomLoadedMsg{panel: panel, chatID: chatID, loadID: loadID, messages: messages, err: err}
	}
}

// applyWallZoomLoaded — ответ на загрузку переписки.
//
// Сверка источника И номера попытки — обязательная часть, а не страховка: в
// широком режиме курсор стены открывает переписку каждого нового источника, и
// пока в полёте несколько запросов, применить можно ровно один — тот, что
// относится к источнику под курсором сейчас. Без сверки быстрое движение
// стрелкой по стене показывало бы переписку предыдущего источника (или вовсе
// пустоту, пока не пришёл его ответ).
//
// Курсор после загрузки — на последнем сообщении: переписку открывают, чтобы
// прочитать свежее, а не чтобы искать начало. Окно прижимается к низу тем же
// scrollTopToBottom, что и стена при первой загрузке.
func (m Model) applyWallZoomLoaded(msg wallZoomLoadedMsg) Model {
	// Сверка идёт по СВОЕЙ панели ответа: переписка ищется там, для кого
	// запросили историю. Поиск по m.zoom (фокусной панели) при двух открытых
	// применил бы ответ панели 2 к панели 1, и чат из второй колонки тихо
	// показался бы в первой.
	zoom := m.panelZoom(msg.panel)
	if zoom == nil || zoom.chatID != msg.chatID || zoom.loadID != msg.loadID {
		return m
	}
	zoom.loading = false
	if msg.err != nil {
		zoom.messages = nil
		zoom.cursor = 0
		zoom.scrollTop = 0
		return m
	}
	zoom.messages = append([]auth.Message(nil), msg.messages...)
	zoom.cursor = max(0, len(zoom.messages)-1)
	zoom.scrollTop = scrollTopToBottom(zoomCardHeight, m.zoomCardsOf(zoom, zoom.messages),
		zoom.cursor, m.zoomListWidthFor(zoom.panel), m.wallZoomListHeight())
	return m
}

// openWallZoom — открыть переписку источника и начать её грузить.
//
// Одна функция на оба способа открытия (явный Enter в узком режиме и
// автоследование за курсором стены в широком): различаются они только поводом
// вызова, а состояние и команда загрузки заводит ровно одно место.
//
// Счётчик loadID живёт на Model, а не внутри wallZoom, и растёт монотонно за
// всю жизнь программы. Внутри структуры он обнулялся бы при каждом новом
// wallZoom, и тогда повторное открытие ТОГО ЖЕ источника начиналось бы с
// loadID = 1 — а устаревший ответ предыдущего открытия совпал бы с ним по обоим
// признакам и применился бы поверх текущего состояния.
//
// Активная цель ответа при этом НЕ снимается: она зафиксирована на конкретное
// сообщение (см. startReply), и молча гасить её только потому, что курсор стены
// оказался на другом источнике, значило бы выбросить сделанный человеком выбор.
// Панель покажет другой источник, а строка ответа над полем — тот, к которому
// ответ и уйдёт; это тот же контракт, что и на стене (цель не едет за курсором).
func (m Model) openWallZoom(chatID int64, title string) (Model, tea.Cmd) {
	return m.openWallZoomIn(panelChat1, chatID, title)
}

// openWallZoomIn — открыть переписку источника в КОНКРЕТНОЙ панели и начать её
// грузить.
//
// Номер панели идёт параметром и в запрос, и в ответ (wallZoomLoadedCmd): без
// него при двух параллельных загрузках панели 1 и 2 сверка (chatID, loadID) в
// applyWallZoomLoaded может совпасть с чужой панелью — те же два источника,
// открытые дважды, дают одинаковую пару признаков, и ответ второй панели
// применился бы к первой.
//
// Панель 1 остаётся «ездящей за курсором стены», панель 2 — закреплённой: её
// меняют только явными командами (Ctrl+2 и Enter из ленты), см. syncWallZoomToCursor.
func (m Model) openWallZoomIn(panel wallPanel, chatID int64, title string) (Model, tea.Cmd) {
	m.zoomLoadID++
	zoom := &wallZoom{
		chatID:  chatID,
		title:   title,
		loading: true,
		loadID:  m.zoomLoadID,
		panel:   panel,
	}
	m.setPanelZoom(panel, zoom)
	return m, m.wallZoomLoadedCmd(panel, chatID, m.zoomLoadID)
}

// closeWallZoom — закрыть переписку и вернуться к стене.
//
// Только для узкого режима: в широком переписке закрываться некуда, она всегда
// показывает источник под курсором (см. слой отмены в Update). Курсор и окно
// стены не трогаются: они относятся к стене, а не к переписке, и после
// возврата человек обязан увидеть её ровно в том месте, где остановился.
func (m Model) closeWallZoom() Model {
	m.zoom = nil
	m.zoomFocused = false
	return m
}

// openWallCursorZoom — открыть переписку источника под курсором стены. Общая
// точка для явного Enter в узком режиме и для автоследования в широком.
//
// Молча выходит, если отправить некуда: пустой поток (закрывать нечего) или
// карточка без chat_id (такое бывает только в тестовых фикстурах, у живых
// данных TDLib id у чата всегда ненулевой).
func (m Model) openWallCursorZoom() (Model, tea.Cmd) {
	return m.openWallCursorZoomIn(panelChat1)
}

// openWallCursorZoomIn — открыть источник под курсором стены в указанной панели.
//
// Номер панели параметром, а не всегда в первую: Ctrl+1 и Ctrl+2 открывают
// источник в своих панелях (решение человека, 2026-10-01), и панель без
// обработчика открылась бы всегда в первой — то есть Ctrl+2 был бы мёртвой
// клавишей.
//
// Панели, которой при текущей ширине нет, номер схлопывается в первую: в обычном
// широком режиме панель одна, и нажатие любой из клавиш открывает её же, а не
// отказывает.
func (m Model) openWallCursorZoomIn(panel wallPanel) (Model, tea.Cmd) {
	if len(m.cards) == 0 {
		return m, nil
	}
	target := m.cards[clampWallCursor(m.cursor, len(m.cards))]
	if target.ChatID == 0 {
		return m, nil
	}
	return m.openWallZoomIn(m.resolvePanel(panel), target.ChatID, target.title())
}

// resolvePanel — панель, в которой действительно можно открыть переписку: та,
// что запрошена, если она существует при текущей ширине терминала, иначе первая.
func (m Model) resolvePanel(panel wallPanel) wallPanel {
	for _, existing := range m.wallChatPanelsOrder() {
		if existing == panel {
			return panel
		}
	}
	return panelChat1
}

// syncWallZoomToCursor — в широком режиме держать открытую переписку на том
// источнике, на котором стоит курсор стены (master-detail превью: переписка
// следует за выбором в списке).
//
// Переоткрытие происходит только когда источник ДЕЙСТВИТЕЛЬНО сменился. Курсор
// стены меняет индекс и по живым апдейтам (перестановка карточек, слежение за
// свежим), а источник там остаётся прежним — и дёргать сеть на каждый кадр
// тогда, когда панель уже показывает нужное, нельзя. Обратная сторона: инвариант
// «панель показывает источник под курсором» держится и в этом случае, потому что
// смена источника — единственное условие переоткрытия.
//
// Отдельный вызов, а не проверка внутри openWallZoom, потому что у вызывающих
// мест разный повод (движение курсором, приход стены, ресайз, живой апдейт), а
// правило одно.
func (m Model) syncWallZoomToCursor() (Model, tea.Cmd) {
	if !m.wallPanelMode() {
		return m, nil
	}
	// При ОДНОЙ панели — старая логика без изменений: панель просто едет за
	// курсором, и никакого «свободная / зафиксированная» тут нет (решение
	// человека, 2026-10-01). Новый круг живёт только там, где есть две панели.
	if !m.wallTwoPanelMode() {
		return m.openWallCursorZoomIfChanged(panelChat1)
	}
	// Две панели: за курсором едет СВОБОДНАЯ, а вторая держит зафиксированный
	// чат. Enter меняет их местами (см. fixPreviewPanel), поэтому «свободная» —
	// это единственное, что нужно помнить сверх содержимого панелей.
	return m.openWallCursorZoomIfChanged(m.previewPanel)
}

// openWallCursorZoomIfChanged — открыть источник под курсором в указанной
// панели, если там открыт другой чат.
//
// Проверка на «уже тот же чат» обязательна: без неё каждое движение курсора
// обрывало бы прежнюю подписку на живые сообщения и начинало новую — при
// перерисовке кадра это запрос к TDLib на каждый кадр.
func (m Model) openWallCursorZoomIfChanged(panel wallPanel) (Model, tea.Cmd) {
	if zoom := m.panelZoom(panel); zoom != nil && len(m.cards) > 0 {
		target := m.cards[clampWallCursor(m.cursor, len(m.cards))]
		if zoom.chatID == target.ChatID {
			return m, nil
		}
	}
	return m.openWallCursorZoomIn(panel)
}

// insertWallZoomMessage — живое сообщение в открытую переписку.
//
// Отдельный путь не по привычке: переписка рисуется из m.zoom.messages, а живое
// сообщение клалось только в карточку стены (applyWallMessageUpdate). Без
// этого сообщение в открытом чате не появлялось бы на экране вовсе — карточка
// источника обновилась бы, а та же переписка рядом осталась бы старой.
//
// Курсор повторяет правило стены: если человек читал последнее сообщение, он
// остаётся в хвосте и новое видно сразу; если поднялся в историю — его не
// выбрасывает вниз, иначе чат дёргался бы на каждом входящем.
func (m *Model) insertWallZoomMessage(chatID int64, message auth.Message) {
	if m.zoom == nil || chatID == 0 || m.zoom.chatID != chatID {
		return
	}
	for _, existing := range m.zoom.messages {
		if existing.ID == message.ID {
			return
		}
	}
	wasAtLatest := len(m.zoom.messages) == 0 || m.zoom.cursor >= len(m.zoom.messages)-1
	m.zoom.messages = insertSortedWallZoomMessage(m.zoom.messages, message)
	if wasAtLatest {
		m.zoom.cursor = max(0, len(m.zoom.messages)-1)
	}
	m.zoom.scrollTop = clampScrollToCursor(zoomCardHeight, m.zoomCardsOf(m.zoom, m.zoom.messages), m.zoom.scrollTop, m.zoom.cursor, m.zoomListWidth(), m.wallZoomListHeight())
}

// insertSortedWallZoomMessage — вставка в переписку по времени сообщения.
// История приходит отсортированной, а живое сообщение может прийти с любой
// датой, поэтому позиция ищется сравнением, а не дописыванием в конец: сообщение
// «из прошлого» в конце переписки читалось бы как следующее по порядку.
func insertSortedWallZoomMessage(list []auth.Message, message auth.Message) []auth.Message {
	position := len(list)
	for index, existing := range list {
		if message.Date < existing.Date {
			position = index
			break
		}
	}
	list = append(list, auth.Message{})
	copy(list[position+1:], list[position:])
	list[position] = message
	return list
}

// selectedWallZoomMessage — сообщение под курсором переписки, если оно есть.
//
// Из ПАНЕЛИ В ФОКУСЕ, а не всегда из первой: при двух панелях фокус может стоять
// на второй, и брать m.zoom значило бы отвечать и удалять в первом чате, пока
// человек смотрит на второй.
func (m Model) selectedWallZoomMessage() (auth.Message, bool) {
	zoom := m.focusedZoom()
	if zoom == nil || len(zoom.messages) == 0 {
		return auth.Message{}, false
	}
	cursor := clampWallCursor(zoom.cursor, len(zoom.messages))
	message := zoom.messages[cursor]
	if message.ID == 0 {
		return auth.Message{}, false
	}
	return message, true
}

// moveWallZoomCursor — курсор переписки на delta сообщений, окно едет за ним
// тем же механизмом, что и на стене.
//
// Из ПАНЕЛИ В ФОКУСЕ, и ширина окна — по её номеру, а не по первой панели:
// при двух панелях у них своя ширина каждая (см. zoomListWidthFor), и мерить
// окно второй переписки по ширине первой значило бы прокручивать не по той
// картине, что нарисована.
func (m *Model) moveWallZoomCursor(delta int) {
	zoom := m.focusedZoom()
	if zoom == nil {
		return
	}
	zoom.cursor = clampWallCursor(zoom.cursor+delta, len(zoom.messages))
	zoom.scrollTop = clampScrollToCursor(zoomCardHeight, m.zoomCardsOf(zoom, zoom.messages),
		zoom.scrollTop, zoom.cursor, m.zoomListWidthFor(zoom.panel), m.wallZoomListHeight())
}

// pageWallZoom — прокрутка переписки на страницу. Страница — это высота зоны
// переписки, а не число сообщений: сообщения разной высоты, и десять коротких
// занимают совсем не то же место, что десять длинных.
//
// Панель и ширина — по фокусу, как и в moveWallZoomCursor.
func (m *Model) pageWallZoom(delta int) {
	zoom := m.focusedZoom()
	if zoom == nil {
		return
	}
	width := m.zoomListWidthFor(zoom.panel)
	cards := m.zoomCardsOf(zoom, zoom.messages)
	top := scrollPageTop(zoomCardHeight, cards, zoom.scrollTop, zoom.cursor, width, m.wallZoomListHeight(), delta)
	if top == zoom.scrollTop {
		// Окно упёрлось в край переписки, а курсор ещё может идти дальше в ту же
		// сторону. Оставлять его на месте нельзя: PgUp у самого старого сообщения
		// перестал бы что-либо делать, и до начала переписки пришлось бы добираться
		// стрелками по одному. Доехал до края — встал на край, как в less и vim.
		edge := 0
		if delta > 0 {
			edge = len(cards) - 1
		}
		zoom.cursor = clampWallCursor(edge, len(cards))
		zoom.scrollTop = clampScrollToCursor(zoomCardHeight, cards, zoom.scrollTop, zoom.cursor, width, m.wallZoomListHeight())
		return
	}
	zoom.cursor = clampWallCursor(zoom.cursor+top-zoom.scrollTop, len(cards))
	zoom.scrollTop = clampScrollToCursor(zoomCardHeight, cards, top, zoom.cursor, width, m.wallZoomListHeight())
}

// wallZoomListWidth — ширина зоны под список переписки. В узком режиме это вся
// ширина терминала (зона стены целиком), в широком — панель справа от колонки
// стены за вычетом её контура: ровно та же поправка, что у wallColumnWidth по
// левой колонке, потому что обе панели обведены контуром одинаковой толщины.
func (m Model) zoomListWidth() int {
	if m.wallPanelMode() {
		// Содержимое ПЕРВОЙ панели переписки, а не всей правой зоны и не той,
		// в которой фокус: в трёхколоночном режиме зона делится на две панели
		// (см. panels.go), и мерять прокрутку по всей зоне значило бы считать
		// окно шире отрисованного.
		//
		// Именно ПЕРВОЙ, а не фокусной: m.zoomListWidth зовёт прокрутка переписки,
		// а прокрутка у m.zoom своя, и панель с этим zoom — первая. Взятая фокусная
		// дала бы нулевую ширину всякому, кто открыл переписку напрямую, минуя
		// focusPanel (тесты и openWallZoom в одиночку), и окно уехало бы в ноль
		// у действующей программы.
		return m.wallPanelListWidth(panelChat1)
	}
	return m.width
}

// zoomListWidthFor — то же, что zoomListWidth, но для КОНКРЕТНОЙ панели.
//
// В узком режиме панелей нет, переписка занимает весь экран, а любая панельная
// ширина равна нулю (панелей нет — см. wallPanelWidths). Через неё
// scrollTopToBottom получал нулевую ширину и отдавал scrollTop = 0: только что
// открытая переписка показывала своё начало вместо хвоста, и PgUp/PgDown от
// начала упирались в край (поймано тестом
// TestPageKeysScrollZoomMessagesInBothModes, узкий случай).
func (m Model) zoomListWidthFor(panel wallPanel) int {
	if !m.wallPanelMode() {
		return m.width
	}
	return m.wallPanelListWidth(panel)
}

// wallZoomListHeight — высота зоны под список переписки: зона стены за вычетом
// шапки (в широком режиме — за вычетом ещё и двух строк контура, см.
// wallContentHeight). И навигация, и отрисовка берут высоту отсюда, а не
// пересчитывают её у себя: две разные формулы разошлись бы, и прокрутка поехала
// бы мимо.
func (m Model) wallZoomListHeight() int {
	return max(0, m.wallContentHeight()-m.zoomHeaderRows())
}

// zoomHeaderRows — сколько строк переписка тратит на шапку с названием источника.
// В компактном режиме шапка своя и обязательная: переписка занимает весь экран и
// больше нигде не называет себя. В широком режиме названия в панели нет — оно
// живёт в верхней строке экрана, и панель отдаёт свою строку списку сообщений.
func (m Model) zoomHeaderRows() int {
	if m.wallPanelMode() {
		return 0
	}
	return wallZoomHeaderRows
}

// zoomCard — сообщение открытой переписки в виде элемента списка.
//
// Это НЕ wallCard: у сообщения в открытом чате нет ни типа источника, ни тега,
// ни имени в каждой строке — всё это уже сказано шапкой экрана. Заголовок,
// время и текст карточки стены задавались бы дважды на каждое сообщение, а метка
// «Вы:» в тексте не нужна: сторону блока говорит выравнивание (card.Outgoing).
//
// Тип карточки стены переиспользуется потому, что окно прокрутки (clampScrollToCursor
// и соседние) считается по []card: завести для переписки второй тип означало бы
// завести рядом второй алгоритм окна, а это ровно то, чего здесь избегали (см.
// cardHeight).
//
// lastReadOutboxMessageID — прочитанный собеседником хвост исходящих (auth.Chat.
// LastReadOutboxMessageID), из снимка чата. Галочка вычисляется ЗДЕСЬ и хранится
// готовым булевым на карточке, а не сравнением id прямо в отрисовке: блок
// сообщения рисуется по карточке, у него нет доступа ни к чату, ни к снимку, и
// перенос сравнения в renderZoomMessage означал бы либо возврат id на карточку
// (лишнее поле ради одного сравнения), либо вторую копию правила в отрисовке.
// Правило — порт messageIsUnreadOutgoing из ленты tgcli (internal/tgclitui/
// feed.go), с обратным смыслом: там спрашивали «не прочитано ли», здесь —
// «прочитано ли».
//
// Нулевое значение lastReadOutboxMessageID (чата нет в снимке — например, в
// тестовой модели) трактуется как «не прочитано»: галочка одна, вслепую
// «прочитано» не показывается никогда.
func zoomCard(message auth.Message, lastReadOutboxMessageID int64) card {
	return card{
		Time:       auth.FormatMessageTime(message.Date),
		Text:       normalizeMessageText(message.Text),
		Date:       message.Date,
		Outgoing:   message.IsOutgoing,
		ReadByPeer: message.IsOutgoing && lastReadOutboxMessageID > 0 && message.ID <= lastReadOutboxMessageID,
		ReplyQuote: message.ReplyQuote,
	}
}

// zoomCards — переписка списком карточек для окна прокрутки. Строится на каждый
// расчёт заново: переписка короткая (предел wallZoomMessagesLimit), а кэш в
// модели означал бы ещё одно состояние, которое надо не забыть сбросить при
// каждой вставке, вгрузке и закрытии — три места, где легко забыть.
// lastReadOutboxMessageID — тот же параметр, что у zoomCard, и по той же
// причине: список и одиночная карточка строятся одним правилом, и разные
// значения на одном экране (у соседних сообщений разошлись бы галочки) взялись
// бы из двух разных вызовов с разными аргументами.
func zoomCards(messages []auth.Message, lastReadOutboxMessageID int64) []card {
	if len(messages) == 0 {
		return nil
	}
	cards := make([]card, 0, len(messages))
	for _, message := range messages {
		cards = append(cards, zoomCard(message, lastReadOutboxMessageID))
	}
	return cards
}

// zoomLastReadOutbox — прочитанный собеседником хвост исходящих открытой
// переписки, из снимка чатов. Единственное место, где берётся это поле, —
// чтобы вызывающие передавали одно и то же значение всем карточкам списка.
//
// Чата, которого нет в снимке, — обычный случай в тестах и не редкость после
// смены снимка: поле у auth.Chat — обычный int64, чтение отсутствующего ключа
// даёт ноль, а ноль прочитано не означает (см. zoomCard).
func (m Model) zoomLastReadOutbox(z *wallZoom) int64 {
	if z == nil {
		return 0
	}
	return m.chatsByID[z.chatID].LastReadOutboxMessageID
}

// zoomCardsOf — карточки переписки для текущего открытого чата. Все вызовы
// zoomCards идут через неё, а не собирают список напрямую: значение
// LastReadOutboxMessageID одно на весь список, и взять его в одном вызывающем
// месте, раздав остальным вручную, значило бы забыть его в следующем новом
// вызове.
// zoomCardsOf — карточки переписки для ПЕРЕПИСКИ z. Все вызовы zoomCards идут
// через неё, а не собирают список напрямую: значение LastReadOutboxMessageID
// одно на весь список, и взять его в одном вызывающем месте, раздав остальным
// вручную, значило бы забыть его в следующем новом вызове.
//
// Переписка передаётся параметром, а не берётся из m.zoom: при двух панелях у
// каждой свой чат и свои галочки, и сборка по фокусной панели нарисовала бы в
// нефокусной чужие отметки о прочтении.
func (m Model) zoomCardsOf(z *wallZoom, messages []auth.Message) []card {
	cards := zoomCards(messages, m.zoomLastReadOutbox(z))
	if accent, ok := m.zoomSelectionAccent(z); ok {
		for index := range cards {
			cards[index].SelectionAccent = accent
		}
	}
	return cards
}

// zoomSelectionAccent — цвет типа ОТКРЫТОГО чата для маркера курсора в
// переписке и признак того, что цвет вообще есть.
//
// Берётся по карточке источника из m.source (полный поток стены), а не из
// m.cards: открытая переписка может показывать источник, скрытый фильтром, и
// тогда у видимого списка карточек его просто не нашлось бы — маркер был бы
// без цвета ровно у того чата, который человек открыл.
//
// Карточки, у которых источника нет в потоке (тестовые фикстуры, чат, ушедший
// со стены), цвета не получают: подставлять вместо него чужой цвет значило бы
// рисовать маркер заведомо неверным тоном, что хуже, чем никакого. То же
// отношение к неизвестному, что и у нулевого LastReadOutboxMessageID —
// «не знаю» не значит «прочитано».
func (m Model) zoomSelectionAccent(z *wallZoom) (color.Color, bool) {
	if z == nil {
		return nil, false
	}
	index := indexOfChatCard(m.source, z.chatID)
	if index < 0 {
		return nil, false
	}
	return m.source[index].accent(), true
}

// zoomCardHeight — сколько строк переписки занимает одно сообщение: строки
// перенесённого текста плюс своя строка времени под ним.
//
// Мера сообщения для окна прокрутки, аналогично wallCardHeight у карточки
// стены. Высота не зависит от выделения: курсор меняет только фон блока, а число
// строк у выбранного и обычного сообщения одинаковое — иначе окно прокрутки
// считало бы по одной картине, а рисовало по другой.
func zoomCardHeight(c card, width int, selected bool) int {
	return len(renderZoomMessage(c, width, selected))
}

// zoomBubbleWidth — ширина блока одного сообщения: доля доступной ширины без
// боковых полей, и не меньше одной ячейки (иначе на очень узкой панели нечего
// рисовать).
func zoomBubbleWidth(width int) int {
	inner := max(0, width-2*cardMarginH)
	return max(1, inner*zoomBubbleMaxWidthPercent/100)
}

// renderZoomMessage — блок одного сообщения переписки: текст, прижатый к
// левому краю у входящего и к правому у своего, и своя строка времени под
// текстом, у того же края.
//
// Время идёт ОТДЕЛЬНОЙ строкой намеренно: в строке с текстом короткое время
// «13:04» растянуло бы короткое сообщение до ширины самой длинной строки и
// выравнивание текста перестало бы значить чьё это сообщение.
//
// Метки «Вы:» здесь нет: сторона и так сказана выравниванием, а лишнее слово в
// каждом своём сообщении только шумит (на стене метка нужна — там все сообщения
// стоят в одной колонке и по стороне неразличимы).
func renderZoomMessage(c card, width int, selected bool) []string {
	if width <= 0 {
		return nil
	}
	// Фон блока — ВСЕГДА тот же, что у экрана (PaletteBackgroundMain), в том числе
	// у сообщения под курсором. Заливка цветом выделения красила прямоугольник
	// даже под короткое «ба», из-за чего сторона выравнивания терялась за пустым
	// цветным полем (человек заметил вживую, 2026-09-30), а снятая по его просьбе
	// (2026-10-01) вдобавок перестала давать что различать: признак «здесь курсор»
	// у переписки один, и это маркер слева от текста, а не заливка.
	background := PaletteBackgroundMain
	inner := max(0, width-2*cardMarginH)
	// markerBlock — сколько ячеек строки занято маркером выбора. Ровно столько же,
	// сколько боковое поле карточки, и совпасть обязано: у входящего маркер
	// стоит ВНУТРИ этого поля, а у своего — встаёт на его место перед текстом, и
	// обе строки собираются по одной формуле с двумя полями по краям зоны.
	// Значение считается из cellWidth того же знака, а не зашито числом: смена
	// глифа не должна молча оставить здесь неверную ширину.
	markerBlock := zoomMarkerBlock()
	bubbleWidth := zoomBubbleWidth(width)
	if c.Outgoing {
		// У своего сообщения маркер стоит перед текстом, то есть ВНУТРИ зоны:
		// без этого урезания на очень узкой панели он вытеснил бы левое поле и
		// встал у края панели — ровно то, чего правка добивается.
		bubbleWidth = min(bubbleWidth, max(1, inner-markerBlock))
	}
	margin := renderedFill(cardMarginH, PaletteBackgroundMain)
	// Время и галочка прочтения — PaletteTextMuted (#888888), а не приглушённым
	// #555555, по прямому слову человека (2026-10-01). Оба знака несли смысл, который
	// на #555555 не читался: время — когда сообщение, галочки — прочитано ли оно
	// собеседником. Оттенок у них общий, а не свой у каждого — различать их
	// между собой незачем, а от текста сообщения (PaletteText) они и отличаются.
	//
	// Фон при этом остаётся основным (PaletteBackgroundMain), а не фоном блока:
	// подпись стоит строкой ниже блока, и её фоном блока продлила бы его вниз.
	time := foregroundBackgroundStyle(PaletteTextMuted, PaletteBackgroundMain).
		Render(truncateVisible(c.Time, cardTimeWidth))
	// Галочка СРАЗУ справа от времени и от него через зазор в одну ячейку — тем же
	// cardSegmentGapWidth, что и все прочие зазоры в этом файле. У ВХОДЯЩЕГО
	// галочек нет никогда: это признак своего сообщения, а входящему прочтение
	// чужого сообщения неотносимо.
	readCheckText := ""
	readCheck := ""
	if c.Outgoing {
		readCheckText = zoomReadCheck(c)
		readCheck = foregroundBackgroundStyle(PaletteTextMuted, PaletteBackgroundMain).Render(readCheckText)
	}
	// Хвост строки времени — всё, что стоит ПРАВЕЕ добивки: время, зазор и
	// галочка. Ширина считается по фактическим символам хвоста, а не по потолку
	// в две галочки: добивка прижата к правому краю зоны, и лишняя ячейка в
	// расчёте сдвинула бы время налево от этого края.
	tailWidth := cellWidth(time)
	// Зазор рисуется только когда галочка есть, — тем же приёмом, что и timeGap
	// у карточки стены: пустой зазор справа от времени съел бы последнюю ячейку
	// зоны, которой на панели и так впритык.
	readGap := ""
	if readCheckText != "" {
		tailWidth += cardSegmentGapWidth + cellWidth(readCheckText)
		readGap = renderedFill(cardSegmentGapWidth, PaletteBackgroundMain)
	}

	// bubbleWidth — потолок для переноса длинных абзацев (wrapVisible), а не
	// ширина, до которой строку надо ДОБИВАТЬ: короткая строка меряется своей
	// собственной шириной, иначе она вставала бы в начало фиксированного блока
	// (левый край bubbleWidth), а не у настоящего края зоны — ровно так, как
	// уже сделано ниже для времени. Человек заметил это вживую (2026-09-30):
	// короткие свои сообщения садились в одну и ту же колонку вместо правого
	// края, хотя фон-плашка (уже убранная) визуально это скрывала.
	//
	// alignedLine — та же арифметика прижатия к своему краю, что и у времени
	// ниже, вынесена в одно место: цитата ответа и строки текста прижимаются
	// одинаково, и вторая копия формулы не должна суметь разойтись с первой.
	//
	// prefix и lead — что стоит по краям текста, в порядке их появления в строке.
	// У входящего prefix — левое поле (у первой строки блока маркер выбора, у
	// остальных и у строки времени обычный margin), а lead пуст: текст идёт
	// сразу за полем. У своего всё наоборот: prefix пуст, а lead — маркер
	// выбора, стоящий вплотную перед текстом (см. marker ниже).
	//
	// Обе роли параметром, а не вычислением внутри: «это первая строка блока» знает
	// вызывающий, и решать это здесь повторно значило бы держать счётчик строк
	// ради одного признака.
	alignedLine := func(prefix, lead, rendered string, textWidth int) string {
		gap := renderedFill(max(0, inner-textWidth), PaletteBackgroundMain)
		if c.Outgoing {
			return prefix + gap + lead + fitLine(rendered, textWidth, background) + margin
		}
		return prefix + fitLine(rendered, textWidth, background) + gap + margin
	}

	lines := make([]string, 0, 3)
	// Маркер выбранного сообщения — только на ПЕРВОЙ строке блока.
	//
	// У ВХОДЯЩЕГО он стоит в левом поле, где сообщение и так прижато к краю, то
	// есть вплотную к тексту. У СВОЕГО сообщение прижато к ПРАВОМУ краю, а левое
	// поле осталось бы на другом конце экрана: маркер стоял бы через всю ширину
	// панели от текста, к которому относится, и перескакивал бы туда-сюда при
	// движении курсором (человек заметил вживую, 2026-10-01). Поэтому у своего
	// маркер переезжает внутрь строки, вплотную перед текстом, а у входящего на
	// его месте остаётся пустое поле той же ширины.
	//
	// Зазор в одну ячейку после знака — тот же cardSegmentGapWidth, что и все
	// прочие зазоры в этом файле: без него «▸» примыкал бы к первой букве
	// текста и читался бы частью слова.
	//
	// Ширина занятого места не зависит от выделения: у невыделенного сообщения
	// там тот же пустой зазор. Иначе строка прыгала бы по ширине вместе с
	// курсором — тот же приём, что у невидимого контура панели (задача 0167)
	// и у левой границы карточки.
	marker := renderedFill(markerBlock, background)
	if selected {
		marker = foregroundBackgroundStyle(c.SelectionAccent, background).
			Render(zoomSelectionMarker) +
			renderedFill(max(0, markerBlock-cellWidth(zoomSelectionMarker)), background)
	}
	// Куда маркер встаёт в этой строке: у входящего он и есть левое поле, у
	// своего — стоит перед текстом. На остальных строках блока маркера нет, и на
	// его месте пустое поле той же ширины.
	firstPrefix, firstLead := marker, ""
	if c.Outgoing {
		firstPrefix, firstLead = "", marker
	}
	restPrefix, restLead := margin, ""
	if c.Outgoing {
		restPrefix, restLead = "", renderedFill(markerBlock, background)
	}

	// Цитата оригинала — знаком ответа (wallReplyMarker), тем же, что и в
	// строке контекста над полем ввода при составлении ответа: карточка
	// переписки иначе никак не отличалась от обычного сообщения (человек
	// заметил вживую, 2026-09-30 — «в чате не видно, что это ответ»). Строкой
	// ВЫШЕ текста, тем же приглушённым цветом, что и там же.
	if c.ReplyQuote != "" {
		prefix := wallReplyMarker + " "
		quote := prefix + truncateVisible(c.ReplyQuote, max(0, bubbleWidth-cellWidth(prefix)))
		rendered := foregroundBackgroundStyle(PaletteTextFaint, background).Render(quote)
		lines = append(lines, alignedLine(firstPrefix, firstLead, rendered,
			min(bubbleWidth, cellWidth(quote))))
		firstPrefix, firstLead = restPrefix, restLead
	}
	for _, text := range wrapVisible(c.Text, bubbleWidth) {
		rendered := highlightText(text, PaletteText, background)
		lines = append(lines, alignedLine(firstPrefix, firstLead, rendered,
			min(bubbleWidth, cellWidth(text))))
		firstPrefix, firstLead = restPrefix, restLead
	}
	if c.Outgoing {
		return append(lines, margin+renderedFill(max(0, inner-tailWidth), PaletteBackgroundMain)+
			time+readGap+readCheck+margin)
	}
	return append(lines, margin+time+renderedFill(max(0, inner-tailWidth), PaletteBackgroundMain)+margin)
}

// Галочки прочтения у СВОЕГО сообщения, тем же видом, что в Telegram: одна —
// отправлено, две — прочитано собеседником.
//
// Знаки вынесены в константы, а не зашиты в renderZoomMessage литералами: ими
// пользуются и отрисовка, и проверки, и разъехаться они могут только разъездом
// записей. У карточки стены галочек нет вовсе (там своя строка времени несёт
// сведения об источнике), поэтому «своё и прочитанное» — это всегда
// c.Outgoing И c.ReadByPeer, а не одно поле: само по себе оно значит лишь
// «прочитано», но не «моё».
const (
	zoomReadCheckSent = "✓"
	zoomReadCheckRead = "✓✓"

	// zoomSelectionMarker — маркер сообщения под курсором переписки, слева от
	// него. Знак выбран тоньше уже принятых в проекте: «▸» (маленький правый
	// треугольник) рядом с «✓» и «↩» читается тем же тонким штрихом, где «▶»
	// был бы тяжелее их обоих и спорил бы с текстом блока.
	zoomSelectionMarker = "▸"
)

// zoomMarkerBlock — сколько ячеек строки занимает маркер выбора сообщения: сам
// знак плюс одна ячейка зазора после него. Это ровно ширина бокового поля
// карточки (cardMarginH), и совпадение обязательно: у входящего сообщения маркер
// стоит внутри этого поля, а у своего встаёт на его место перед текстом — обе
// строки собираются по одной формуле, где поля и маркер занимают одно и то же
// место.
//
// Функция, а не константа: ширина берётся из того же знака, которым рисуется
// маркер, и зашитое число разошлось бы с ним при смене глифа.
func zoomMarkerBlock() int {
	return cellWidth(zoomSelectionMarker) + cardSegmentGapWidth
}

// zoomReadCheck — галочки у исходящего сообщения. Вызывается только для
// c.Outgoing (см. renderZoomMessage): у входящего их нет вообще, и пустая
// строка здесь означала бы «посчитать зазор в никуда».
func zoomReadCheck(c card) string {
	if c.ReadByPeer {
		return zoomReadCheckRead
	}
	return zoomReadCheckSent
}

// renderWallZoomHeader — шапка переписки: название источника, тем же
// заголовком, каким карточка стены называет себя сама (card.title), и в том же
// стиле. Рисуется только в компактном режиме (см. zoomHeaderRows).
//
// focused — переписка в фокусе: тогда строка шапки залита фоном выделения.
// Это единственный признак «фокус сейчас здесь» в компактном режиме: переписка
// занимает весь экран и больше нигде не называет себя. В широком режиме фокус
// показывает контур панели.
func renderWallZoomHeader(title string, width int, focused bool) string {
	background := PaletteBackgroundMain
	if focused {
		background = PaletteBackgroundSelected
	}
	inner := max(0, width-2*cardMarginH)
	margin := renderedFill(cardMarginH, background)
	style := lipgloss.NewStyle().Foreground(PaletteText).Bold(true).Background(background)
	return margin + fitLine(style.Render(truncateVisible(title, inner)), inner, background) + margin
}

// renderWallZoomMessages — список сообщений переписки заданной ширины и
// высоты. Единственная отрисовка переписки на обе её ширины: полноэкранный
// режим и правая панель вызывают её одинаково, различается только аргумент.
//
// Окно пересчитывается здесь тем же clampScrollToCursor, что и в навигации, но
// в локальную переменную: отрисовка не имеет права менять состояние, а навигация
// уже привела scrollTop в границы — повторный расчёт на тех же данных даёт тот
// же самый результат и заодно страхует от любого пути, который его забыл.
func (m Model) renderWallZoomMessages(zoom *wallZoom, width, height int) []string {
	if width <= 0 || height <= 0 {
		return nil
	}
	// nil ПРОВЕРЯЕТСЯ РАНЬШЕ загрузки: у пустой панели нет и m.zoom, к которому
	// обращалась бы проверка загрузки, — порядок наоборот даёт разыменование nil
	// в тот самый момент, когда вторая панель ещё не открыта.
	if zoom == nil {
		return backgroundLines(width, height)
	}
	if zoom.loading {
		return zoomNoticeLines("Загрузка истории…", width, height)
	}
	cards := m.zoomCardsOf(zoom, zoom.messages)
	if len(cards) == 0 {
		return zoomNoticeLines("Нет сообщений", width, height)
	}
	top := clampScrollToCursor(zoomCardHeight, cards, zoom.scrollTop, zoom.cursor, width, height)
	return renderCardList(cards, top, zoom.cursor, width, height, renderZoomMessage)
}

// zoomNoticeLines — одна приглушённая строка-заглушка на месте переписки и добивка
// фоном до высоты зоны. Тексты взяты из того, что известно наверняка, и не
// выдуманы, — тот же принцип, что у заглушки пустой стены (см. wallNotice).
func zoomNoticeLines(text string, width, height int) []string {
	notice := fitLine(
		renderedFill(cardMarginH, PaletteBackgroundMain)+
			foregroundBackgroundStyle(PaletteTextFaint, PaletteBackgroundMain).Render(truncateVisible(text, max(0, width-2*cardMarginH)))+
			renderedFill(cardMarginH, PaletteBackgroundMain),
		width, PaletteBackgroundMain)
	lines := make([]string, 0, height)
	lines = append(lines, notice)
	for len(lines) < height {
		lines = append(lines, backgroundLines(width, 1)[0])
	}
	return lines
}

// backgroundLines — height строк основного фона шириной width. Заглушка зоны, у
// которой нет содержимого: панель переписки на широком терминале до прихода
// первого ответа загрузки.
func backgroundLines(width, height int) []string {
	if width <= 0 || height <= 0 {
		return nil
	}
	line := renderedFill(width, PaletteBackgroundMain)
	lines := make([]string, 0, height)
	for range height {
		lines = append(lines, line)
	}
	return lines
}

// renderWallZoomColumn — колонка переписки целиком: шапка и список сообщений.
//
// Ширина и высота на входе — те, что достались зоне: в узком режиме это весь
// экран, в широком — панель справа от колонки стены. Внутри шапка занимает
// m.zoomHeaderRows() строк, списку остаётся остальное, и обе части в сумме дают
// ровно заданную высоту, как и требует каркас экрана. То же число берёт
// wallZoomListHeight, на которую опирается прокрутка.
// renderWallZoomColumn — колонка переписки КОНКРЕТНОЙ панели целиком: шапка и
// список сообщений. Панель передаётся параметром, а не берётся из m.zoom: при двух
// панелях у каждой своя переписка, и колонка второй нарисовала бы по содержимому
// первой.
//
// Ширина и высота на входе — те, что достались зоне: в узком режиме это весь
// экран, в широком — панель справа от колонки стены. Внутри шапка занимает
// m.zoomHeaderRows() строк, списку остаётся остальное, и обе части в сумме дают
// ровно заданную высоту, как и требует каркас экрана. То же число берёт
// wallZoomListHeight, на которую опирается прокрутка.
func (m Model) renderWallZoomColumn(zoom *wallZoom, width, height int) []string {
	if width <= 0 || height <= 0 {
		return nil
	}
	headerRows := m.zoomHeaderRows()
	lines := make([]string, 0, height)
	if headerRows > 0 && zoom != nil {
		lines = append(lines, renderWallZoomHeader(zoom.title, width, m.panelFocused(zoom.panel)))
	}
	listHeight := max(0, height-headerRows)
	lines = append(lines, m.renderWallZoomMessages(zoom, width, listHeight)...)
	for len(lines) < height {
		lines = append(lines, renderedFill(width, PaletteBackgroundMain))
	}
	return lines
}

// renderWallZone — зона «стена» экрана целиком. Три случая, один компонент
// переписки (renderWallZoomMessages) и одна карточка стены (renderCard) на всех:
//
//   - узкий терминал, переписка не открыта — стена во всю ширину;
//   - узкий терминал, переписка открыта — переписка во всю ширину вместо стены;
//   - широкий терминал — колонка стены и панель переписки рядом, через зазор в
//     wallPanelGapWidth, обе обведены контуром.
//
// Отдельные пути отрисовки у первых двух случаев не заводятся: это один и тот же
// список сообщений, отличается только ширина, ради которой он и берётся
// параметром.
func (m Model) renderWallZone(width, height int) []string {
	if width <= 0 || height <= 0 {
		return nil
	}
	if !m.wallPanelMode() {
		if m.zoom != nil {
			return m.renderWallZoomColumn(m.zoom, width, height)
		}
		return renderWallWith(m.cards, m.scrollTop, m.cursor, width, height, m.wallNotice(), m.renderWallCardBlock)
	}

	// Сначала ВСЯ панель (с контуром), потом её содержимое. Ширины содержимого
	// берутся из тех же функций, по которым считается окно прокрутки
	// (wallColumnWidth, wallPanelListWidth), а высота — из третьей
	// (wallContentHeight): иначе окно мерилось бы по одной ширине и высоте, а
	// рисовало по другой.
	//
	// Место под контур вычитается здесь, а не внутри panelOutline: тот оборачивает
	// ГОТОВЫЕ строки и ничего не знает ни о ширине терминала, ни о колонках зоны.
	//
	// Без открытой переписки контура нет (см. wallPanelOutlined), и тогда место под
	// него возвращается содержимому всех колонок — иначе строка зоны оказалась бы
	// уже терминала на четыре ячейки, а панели справа (пустой фон) не рисовалось
	// бы вовсе.
	panelHeight, leftWidth := height, wallPanelColumnWidth
	if m.wallPanelOutlined() {
		panelHeight = panelContentHeightFor(height)
		leftWidth = m.wallColumnWidth()
	}

	// Колонка стены рисуется ТЕМ ЖЕ renderWallCardBlock, а не обычным renderWall:
	// иначе флаг «у карточки под курсором нет времени и превью» остался бы
	// свойством тестового хелпера, а на экране карточка выводила бы ровно то, что
	// и так целиком видно справа.
	left := renderWallWith(m.cards, m.scrollTop, m.cursor, leftWidth, panelHeight, m.wallNotice(), m.renderWallCardBlock)
	// Колонки переписки — по одной на каждую панель, в порядке их номеров: при
	// трёхколоночном режиме их две, при обычном широком одна, и обе собираются
	// одним циклом, а не двумя разными ветками (иначе ширины и высоты панелей
	// разошлись бы между собой при первой же правке).
	chats, chatWidths := m.renderWallChatColumns(panelHeight)

	// Все колонки доводятся до общей высоты ДО склейки: renderWall на пустой
	// стене возвращает одну строку-заглушку вместо всей высоты зоны (её добивает
	// каркас экрана), и без добивки строки колонок разошлись бы по высоте.
	left = zoneColumn(left, leftWidth, panelHeight)
	chats = zoneColumns(chats, chatWidths, panelHeight)

	columns := make([][]string, 0, 1+len(chats))
	columns = append(columns, left)
	columns = append(columns, chats...)

	// Контур замыкает колонки до ПОЛНОЙ высоты зоны: рамка не добавляет зоне
	// строк, она перераспределяет уже отведённые — между собой и содержимым.
	if m.wallPanelOutlined() {
		for index, panel := range m.wallChatPanelsOrder() {
			columns[index+1] = panelOutline(columns[index+1], m.wallPanelWidth(panel), height,
				m.panelFocused(panel), m.panelAccent(panel))
		}
		columns[0] = panelOutline(left, wallPanelColumnWidth, height, !m.focusPanel.isChatPanel(), m.wallAccent())
	}
	gap := renderedFill(wallPanelGapWidth, PaletteBackgroundMain)
	lines := make([]string, 0, height)
	for row := range height {
		row2 := make([]string, 0, len(columns))
		for _, column := range columns {
			row2 = append(row2, column[row])
		}
		// Поле справа от крайней панели — последним куском строки: рамка панели
		// не должна стоять вплотную к краю терминала (см.
		// wallPanelInsetRight). Добавляется здесь, а не вычитается из ширины
		// панели, потому что ширины панелей одинаковы у всех, а поле нужно ровно
		// одно — у самой правой.
		joined := strings.Join(row2, gap)
		if tail := max(0, width-cellWidth(joined)); tail > 0 {
			joined += renderedFill(tail, PaletteBackgroundMain)
		}
		lines = append(lines, joined)
	}
	return lines
}

// renderWallChatColumns — колонки переписки, по одной на каждую панель, в порядке
// номеров. Панели, в которых ничего не открыто, рисуются пустым фоном той же
// ширины: место под них зарезервировано всегда, иначе панель появлялась бы и
// исчезала бы вместе с открытием переписки, а раскладка прыгала бы на её ширину.
func (m Model) renderWallChatColumns(height int) ([][]string, []int) {
	order := m.wallChatPanelsOrder()
	columns := make([][]string, 0, len(order))
	widths := make([]int, 0, len(order))
	for _, panel := range order {
		widths = append(widths, m.wallPanelWidth(panel))
		columns = append(columns, m.renderWallZoomColumn(m.panelZoom(panel), widths[len(widths)-1], height))
	}
	return columns, widths
}

// zoneColumns — добивка колонок переписки до общей высоты. Тот же приём, что у
// zoneColumn, но сразу для всех панелей: одна функция на цикл в renderWallZone
// значила бы писать добивку вручную для каждой и забыть про вторую.
func zoneColumns(columns [][]string, widths []int, height int) [][]string {
	for index, column := range columns {
		columns[index] = zoneColumn(column, widths[index], height)
	}
	return columns
}

// wallPanelOutlined — рисуется ли контур панелей широкого режима. Он отвечает на
// вопрос «где сейчас фокус», а фокусировать в широком режиме нечего, пока
// переписка не открыта: без неё панели справа нет (там пустой фон), переключать
// нечего, и zoomHasFocus тоже возвращает false — Tab в таком состоянии и не
// перехватывается (см. обработчик Tab в Update).
//
// Единое условие и для отрисовки контура, и для вычета под него места: если бы
// одно из двух решало само по себе, панели разъехались бы по высоте (контур
// нарисован, а место не вычтено — или наоборот).
func (m Model) wallPanelOutlined() bool {
	// Контур рисуется в широком режиме ВСЕГДА, а не только при открытой
	// переписке. Он отвечает на вопрос «где сейчас фокус», а не «есть ли чат»:
	// требование открытой переписки означало, что на свежей стене, где чатов
	// ещё нет, не было видно НИ ОДНОГО контура — ни у ленты (фокус на ней), ни у
	// пустых панелей, и человек не видел, где находится выделение, пока что-то
	// не открывал.
	//
	// Пустая панель получает контур цвета фона, то есть невидимый: место под
	// него зарезервировано, и появление переписки не сдвинет содержимое.
	return m.wallPanelMode()
}

// panelAccent — цвет типа ОТКРЫТОГО чата в указанной панели: им красится её
// контур, когда в ней фокус.
//
// Карточка ищется по chatID переписки во всём потоке стены (m.source), а не по
// m.cards: открытая переписка принадлежит именно этому источнику, и по
// отфильтрованному списку её карточка могла бы не найтись — тогда контур остался
// бы бесцветным в момент, когда человек как раз смотрит на переписку.
//
// Без найденной карточки (источник убран со стены, пока переписка открыта) тип
// неизвестен, и контур остаётся фоном — то есть невидимым. Это не молчаливая
// потеря цвета, а честное «типа нет»: красить его цветом какого-то другого
// источника было бы враньём на экране.
func (m Model) panelAccent(panel wallPanel) color.Color {
	zoom := m.panelZoom(panel)
	if zoom == nil {
		return PaletteBackgroundMain
	}
	if index := indexOfChatCard(m.source, zoom.chatID); index >= 0 {
		return m.source[index].accent()
	}
	return PaletteBackgroundMain
}

// zoneColumn — строки зоны, добитые до height. Нужна для склейки колонок
// широкого режима (см. renderWallZone).
func zoneColumn(lines []string, width, height int) []string {
	if width <= 0 || height <= 0 {
		return nil
	}
	for len(lines) < height {
		lines = append(lines, renderedFill(width, PaletteBackgroundMain))
	}
	return lines
}

// panelOutline — оборачивает готовые строки панели тонким контуром со всех
// четырёх сторон. Помощник общий и ничего не знает ни о стене, ни о переписке:
// на входе уже готовые строки содержимого, на выходе — строки той же панели
// целиком. Место под контур вычтено из содержимого ДО вызова (см.
// wallPanelOutlineInset, renderWallZone).
//
// Контур зарезервирован ВСЕГДА: у панели без фокуса он не исчезает, а просто
// рисуется цветом фона, то есть невидим. Прятать его по-настоящему (рисовать
// только у панели в фокусе) нельзя — тогда содержимое сдвинулось бы на две
// ячейки и на две строки в момент нажатия Tab. Тот же приём, что у левой
// границы карточки (renderWallCard).
//
// Глифы — толстая рамка (┏━┓┃┗┛), а не лёгкая (┌─┐│└┘), и это не украшение:
// вертикаль в интерфейсе стены всюду толстая (граница карточки ┃, граница блока
// ввода ┃ — решение человека, тонкая │ на тёмном фоне терялась, см.
// chatZoneBorderGlyph в tgclitui), а лёгкая рамка завела бы в тот же экран
// вторую вертикаль и выглядела бы рядом с границей карточки чужой.
func panelOutline(content []string, width, height int, focused bool, accent color.Color) []string {
	if width <= 0 || height <= 0 {
		return nil
	}
	// Рамке негде рисоваться: на панель в две ячейки или в две строки места под
	// контур не хватает, и остаётся только фон — ровно та же высота, что
	// отдала панель.
	if width < 2 || height < 2 {
		return backgroundLines(width, height)
	}
	// Контур без фокуса — тёмно-серый PalettePanelBorder, а НЕ цвет фона: панель
	// должна читаться как отдельная колонка и без фокуса, иначе в трёхколоночном
	// режиме правая часть экрана читалась бы как пустое поле без границ. С
	// фокусом — акцент типа открытого чата (решение человека, 2026-10-01).
	borderColor := PalettePanelBorder
	if focused {
		borderColor = accent
	}
	style := foregroundBackgroundStyle(borderColor, PaletteBackgroundMain)
	inner := width - 2
	side := style.Render("┃")
	horizontal := strings.Repeat("━", inner)
	lines := make([]string, 0, height)
	lines = append(lines, style.Render("┏"+horizontal+"┓"))
	for _, row := range content {
		if len(lines) == height-1 {
			// Нижняя граница нужна последней, и лишняя строка содержимого за
			// содержимым панели не должна была бы вытеснить её за пределы панели.
			break
		}
		// fitLine, а не row как есть: строка короче отведённой ширины утянула бы
		// за собой всю строку зоны (каркас склеивает колонки построчно, и минус
		// одна ячейка уехал бы на всю сетку экрана).
		lines = append(lines, side+fitLine(row, inner, PaletteBackgroundMain)+side)
	}
	fill := side + renderedFill(inner, PaletteBackgroundMain) + side
	for len(lines) < height-1 {
		lines = append(lines, fill)
	}
	return append(lines, style.Render("┗"+horizontal+"┛"))
}

// renderWallCardBlock — карточка стены в том виде, в каком она рисуется сейчас:
// в широком режиме у карточки под курсором не показываются ни время, ни текст
// последнего сообщения — та же переписка открыта справа целиком.
//
// Флаг выводится из одного места (renderCardList передаёт сюда «это элемент под
// курсором»), иначе «карточка под курсором» нашлась бы отдельно в отрисовке и
// отдельно в счётчиках тестов, и рано или поздно разошлась бы.
func (m Model) renderWallCardBlock(c card, width int, underCursor bool) []string {
	panel := m.wallPanelMode()
	return renderWallCard(c, width, underCursor, panel && underCursor, panel)
}

// zoomReplyLabel — строка «на что отвечаем» для ответа на сообщение открытой
// переписки. Тот же вид, что у карточки стены (replyLabel): заголовок источника и
// усечённый кусок текста.
//
// Заголовок берётся как есть — openWallZoom кладёт в title ровно card.title(),
// уже со скобками. Скобки не добавляются здесь: повторная обёртка дала бы
// «[[Андрей]]».
//
// Название источника здесь не лишнее, хотя его и показывает шапка: строка ответа
// стоит под всем экраном, и на широком терминале между ней и шапкой панели лежит
// колонка карточек стены.
func zoomReplyLabel(zoom *wallZoom, message auth.Message) string {
	return replyPreviewLabel(zoom.title, normalizeMessageText(message.Text))
}
